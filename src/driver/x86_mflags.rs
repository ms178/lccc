//! The x86 machine options without code generation of their own.
//!
//! The main argument loop has an arm for every `-m` option the compiler
//! implements. What none of them takes used to end in two catch-alls: an
//! option was an error, its `-mno-` form was accepted without a word.
//! Measured against GCC 16.2's own list that refused 119 spellings GCC
//! accepts and swallowed 81, and it was wrong both ways: `-mlong-double-80`
//! asks for what the compiler does and stopped the build, while
//! `-mno-tls-direct-seg-refs` asks for what it does not do and was waved
//! through.
//!
//! `x86_mflag_policy` (generated by `scripts/gen_x86_mflag_policy.py`,
//! which has the reasons and the measurements) decides every such
//! spelling, per mode. This module reads the table for one argument:
//!
//! * [`is_decided`]: whether the table has the spelling at all, asked by
//!   the argument loop, which then keeps the argument for later;
//! * [`decide`]: the outcome once the target (`-m32` may follow the
//!   option) and the ISA are known;
//! * [`expand_aliases`]: the options GCC keeps as names for other
//!   options, replaced before anything reads the command line.

use super::x86_mflag_policy::{
    ALIASES, BOOLEAN, Modes, OBSOLETE_ALIGN, OtherValue, PREFIX_ALIASES, VALUED, Verdict,
};

/// What to do with one argument.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) enum Outcome {
    /// Nothing: what is asked is what the compiler does.
    State,
    /// Warn that nothing acts on it; the reason.
    Hint(&'static str),
    /// Warn in GCC's words and do nothing.
    Ignored(String),
    /// An error: the reason.
    Refused(String),
    /// An error in GCC's words.
    Invalid(String),
}

/// The state of the command line a decision can depend on.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub(crate) struct Context {
    /// x86-64, not IA-32.
    pub x86_64: bool,
    /// APX code generation is on (`-mapxf`).
    pub apx: bool,
    /// `__CRC32__` is defined: SSE4.2 is enabled, or held by
    /// `-mgeneral-regs-only`.
    pub crc32: bool,
    /// SSE3 is enabled.
    pub sse3: bool,
}

/// The table's row for `-mNAME` / `-mno-NAME`, and whether the argument
/// is the `-mno-` form. A name that itself begins with `no` (`-mnoreturn-
/// no-callee-saved-registers`) is tried whole first.
fn boolean(arg: &str) -> Option<Modes> {
    let name = arg.strip_prefix("-m")?;
    let find = |name: &str| {
        BOOLEAN
            .binary_search_by(|row| row.name.cmp(name))
            .ok()
            .map(|at| &BOOLEAN[at])
    };
    if let Some(on) = find(name).and_then(|row| row.on) {
        return Some(on);
    }
    find(name.strip_prefix("no-")?)?.off
}

/// The table's row for `-mNAME=VALUE`: the row and the value.
fn valued(arg: &str) -> Option<(&'static super::x86_mflag_policy::Valued, &str)> {
    let (name, value) = arg.split_once('=')?;
    let at = VALUED
        .binary_search_by(|row| row.prefix[..row.prefix.len() - 1].cmp(name))
        .ok()?;
    Some((&VALUED[at], value))
}

/// Whether the table decides `arg`. `-mcmodel=` has arms of its own for
/// every value but the one IA-32 has.
pub(crate) fn is_decided(arg: &str) -> bool {
    if boolean(arg).is_some() {
        return true;
    }
    match valued(arg) {
        Some((row, value)) => {
            row.other != OtherValue::Checked("elsewhere")
                || row.values.iter().any(|(listed, _)| *listed == value)
        }
        None => false,
    }
}

/// What two occurrences of one option have in common: the name of
/// `-mNAME` and `-mno-NAME`, the prefix of `-mNAME=VALUE`. GCC keeps the
/// last occurrence of each.
pub(crate) fn key(arg: &str) -> &str {
    if let Some((row, _)) = valued(arg) {
        return row.prefix;
    }
    let name = arg.strip_prefix("-m").unwrap_or(arg);
    let whole = BOOLEAN
        .binary_search_by(|row| row.name.cmp(name))
        .is_ok_and(|at| BOOLEAN[at].on.is_some());
    if whole {
        name
    } else {
        name.strip_prefix("no-").unwrap_or(name)
    }
}

fn refused(arg: &str, why: &str) -> Outcome {
    Outcome::Refused(format!("unsupported machine option {arg}: {why}"))
}

fn of_verdict(arg: &str, verdict: Verdict, ctx: &Context) -> Outcome {
    match verdict {
        Verdict::State => Outcome::State,
        Verdict::Hint => Outcome::Hint(TUNING_NOTE),
        Verdict::Ignored(text) => Outcome::Ignored(text.to_string()),
        Verdict::Refused(why) => refused(arg, why),
        Verdict::Invalid(text) => Outcome::Invalid(text.to_string()),
        Verdict::Depends => depends(arg, ctx),
        // An implemented option has an arm in the argument loop and does
        // not come here. Should one, accepting it would be the silence
        // this module exists to end.
        Verdict::Effect => Outcome::Refused(format!(
            "internal error: machine option {arg} is listed as implemented and no arm of the driver took it"
        )),
    }
}

/// What a hint's warning says of it.
const TUNING_NOTE: &str = "it chooses among ways of generating equivalent code";

/// The rows whose answer is another extension's: GCC has a bit of its own
/// for CRC32 and for MWAIT; here the `crc32` instructions are SSE4.2's
/// and `monitor`/`mwait` are SSE3's.
fn depends(arg: &str, ctx: &Context) -> Outcome {
    let (name, parent, option, enabled) = match arg {
        "-mcrc32" | "-mno-crc32" => (
            "`__CRC32__` and the `crc32` intrinsics",
            "SSE4.2",
            "sse4.2",
            ctx.crc32,
        ),
        "-mmwait" | "-mno-mwait" => ("`_mm_monitor` and `_mm_mwait`", "SSE3", "sse3", ctx.sse3),
        _ => return refused(arg, "no rule is known for it"),
    };
    let off = arg.starts_with("-mno-");
    match (off, enabled) {
        (false, true) | (true, false) => Outcome::State,
        (false, false) => refused(
            arg,
            &format!("{name} come with {parent} here and not on their own; use -m{option}"),
        ),
        (true, true) => refused(
            arg,
            &format!(
                "{name} come with {parent} here and cannot be withdrawn alone; use -mno-{option}"
            ),
        ),
    }
}

fn missing(prefix: &str) -> Outcome {
    Outcome::Invalid(format!("missing argument to '{prefix}'"))
}

fn unrecognized(arg: &str) -> Outcome {
    Outcome::Invalid(format!("unrecognized argument in option '{arg}'"))
}

fn not_an_integer(prefix: &str) -> Outcome {
    Outcome::Invalid(format!(
        "argument to '{prefix}' should be a non-negative integer"
    ))
}

/// The value checkers the table names (`OtherValue::Checked`). Every
/// message GCC has for a value is GCC's (16.2, measured).
fn checked(checker: &str, arg: &str, prefix: &'static str, value: &str, ctx: &Context) -> Outcome {
    if value.is_empty() {
        return missing(prefix);
    }
    match checker {
        "branch_cost" => match value.parse::<u32>() {
            Err(_) => not_an_integer(prefix),
            Ok(cost) if cost > 5 => {
                Outcome::Invalid(format!("argument to '{prefix}' is not between 0 and 5"))
            }
            Ok(_) => Outcome::Hint(TUNING_NOTE),
        },
        "incoming_stack_boundary" => {
            let lowest = if ctx.x86_64 { 3 } else { 2 };
            match value.parse::<u32>() {
                Err(_) => not_an_integer(prefix),
                Ok(log2) if !(lowest..=12).contains(&log2) => {
                    Outcome::Invalid(format!("'{arg}' is not between {lowest} and 12"))
                }
                Ok(4) => Outcome::State,
                Ok(log2) if log2 > 4 => {
                    Outcome::Hint("it promises more alignment than is assumed, and nothing uses it")
                }
                Ok(_) => refused(
                    arg,
                    "functions are compiled for a stack that is 16-byte aligned when they are \
                     entered, and cannot realign it",
                ),
            }
        }
        "large_data_threshold" => match value.parse::<u64>() {
            Err(_) => not_an_integer(prefix),
            Ok(_) => refused(
                arg,
                "no object is placed in the large data sections (-mcmodel=medium is compiled as \
                 the small model), so there is no threshold to set",
            ),
        },
        "recip" => {
            for token in value.split(',') {
                let name = token.strip_prefix('!').unwrap_or(token);
                if !matches!(
                    name,
                    "all" | "default" | "none" | "div" | "sqrt" | "vec-div" | "vec-sqrt"
                ) {
                    return Outcome::Invalid(format!("unknown option for '-mrecip={token}'"));
                }
            }
            Outcome::Hint("reciprocal estimates are never generated")
        }
        "free_hint" => Outcome::Hint(TUNING_NOTE),
        "cobol" => Outcome::Ignored(format!(
            "command-line option '{arg}' is valid for Cobol but not for C"
        )),
        "lam" => Outcome::Invalid(format!("unknown lam type '{value}'")),
        "apx_features" => {
            let known = |token: &str| {
                matches!(
                    token,
                    "egpr" | "push2pop2" | "ndd" | "ppx" | "nf" | "ccmp" | "zu" | "all" | "none"
                )
            };
            if !value.split(',').all(known) {
                return unrecognized(arg);
            }
            let withdraws = prefix == "-mno-apx-features=" || value == "none";
            if !withdraws && !ctx.x86_64 {
                return Outcome::Invalid(
                    "'-mapx-features=' option is not supported for 32-bit code".to_string(),
                );
            }
            if withdraws && !ctx.apx {
                return Outcome::State;
            }
            refused(
                arg,
                "APX code generation is selected as a whole by -mapxf; its features cannot be \
                 chosen one by one",
            )
        }
        _ => Outcome::Refused(format!(
            "internal error: machine option {arg} is listed as implemented and no arm of the driver took it"
        )),
    }
}

/// The outcome for `arg`, an argument [`is_decided`] is true for.
pub(crate) fn decide(arg: &str, ctx: &Context) -> Option<Outcome> {
    let pick = |modes: Modes| {
        if ctx.x86_64 { modes.x86_64 } else { modes.ia32 }
    };
    if let Some(modes) = boolean(arg) {
        return Some(of_verdict(arg, pick(modes), ctx));
    }
    let (row, value) = valued(arg)?;
    if let Some((_, modes)) = row.values.iter().find(|(listed, _)| *listed == value) {
        return Some(of_verdict(arg, pick(*modes), ctx));
    }
    Some(match row.other {
        OtherValue::Invalid if value.is_empty() => missing(row.prefix),
        OtherValue::Invalid => unrecognized(arg),
        // The other values have arms of their own in the argument loop.
        OtherValue::Checked("elsewhere") => return None,
        OtherValue::Checked(checker) => checked(checker, arg, row.prefix, value, ctx),
    })
}

/// Replace the options GCC 16.2 keeps as names for other options, and
/// return GCC's warning for each one found.
///
/// The replacement stands where the alias stood, so that what comes later
/// on the command line still wins. `-malign-NAME=N` is the exception GCC
/// makes: it is `-falign-NAME=2^N` only where no `-falign-NAME` is given
/// (measured: an explicit `-falign-functions=64` wins on either side of
/// it), so its replacement goes to the front.
pub(crate) fn expand_aliases(args: &[String]) -> Result<(Vec<String>, Vec<String>), String> {
    let mut front = Vec::new();
    let mut out = Vec::with_capacity(args.len());
    let mut warnings: Vec<String> = Vec::new();
    let mut warn = |text: String| {
        if !warnings.contains(&text) {
            warnings.push(text);
        }
    };
    for arg in args {
        if let Ok(at) = ALIASES.binary_search_by(|(option, ..)| (*option).cmp(arg.as_str())) {
            let (_, warning, replacement) = ALIASES[at];
            warn(warning.to_string());
            out.push(replacement.to_string());
            continue;
        }
        if let Some((_, warning, replacement, value)) =
            PREFIX_ALIASES.iter().find_map(|(prefix, warning, to)| {
                arg.strip_prefix(prefix)
                    .map(|value| (prefix, warning, to, value))
            })
        {
            warn(warning.to_string());
            out.push(format!("{replacement}{value}"));
            continue;
        }
        if let Some((name, value)) = arg
            .strip_prefix("-malign-")
            .and_then(|rest| rest.split_once('='))
            .filter(|(name, _)| OBSOLETE_ALIGN.iter().any(|known| known == name))
        {
            let prefix = format!("-malign-{name}=");
            if value.is_empty() {
                return Err(format!("missing argument to '{prefix}'"));
            }
            let log2: u32 = value
                .parse()
                .map_err(|_| format!("argument to '{prefix}' should be a non-negative integer"))?;
            warn(format!(
                "'-malign-{name}' is obsolete, use '-falign-{name}'"
            ));
            if log2 > 16 {
                return Err(format!("'{arg}' is not between 0 and 16"));
            }
            if log2 != 0 {
                front.push(format!("-falign-{name}={}", 1u32 << log2));
            }
            continue;
        }
        out.push(arg.clone());
    }
    front.append(&mut out);
    Ok((front, warnings))
}

