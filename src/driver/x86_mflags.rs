    /// state where the parent extension agrees and an error where it
    /// does not, in both directions.
    #[test]
    fn an_extension_that_rides_another_follows_it() {
        let with = Context {
            crc32: true,
            sse3: true,
            ..X64
        };
        assert_eq!(outcome("-mcrc32", &with), Outcome::State);
        assert_eq!(outcome("-mno-crc32", &X64), Outcome::State);
        assert!(is_refusal(&outcome("-mcrc32", &X64), "use -msse4.2"));
        assert!(is_refusal(&outcome("-mno-crc32", &with), "use -mno-sse4.2"));
        assert_eq!(outcome("-mmwait", &with), Outcome::State);
        assert_eq!(outcome("-mno-mwait", &X64), Outcome::State);
        assert!(is_refusal(&outcome("-mmwait", &X64), "use -msse3"));
        assert!(is_refusal(&outcome("-mno-mwait", &with), "use -mno-sse3"));
    }

    #[test]
    fn apx_features_cannot_be_chosen_one_by_one() {
        let apx = Context { apx: true, ..X64 };
        assert_eq!(outcome("-mapx-features=none", &X64), Outcome::State);
        assert_eq!(outcome("-mapx-features=none", &IA32), Outcome::State);
        assert_eq!(outcome("-mno-apx-features=egpr,ndd", &X64), Outcome::State);
        assert_eq!(outcome("-mno-apx-features=all", &IA32), Outcome::State);
        for arg in [
            "-mapx-features=egpr",
            "-mapx-features=all",
            "-mapx-features=none,egpr",
        ] {
            assert!(is_refusal(&outcome(arg, &X64), "as a whole"), "{arg}");
        }
        for arg in ["-mapx-features=none", "-mno-apx-features=ndd"] {
            assert!(is_refusal(&outcome(arg, &apx), "as a whole"), "{arg}");
        }
    }

