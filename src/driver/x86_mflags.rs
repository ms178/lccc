    fn strings(args: &[&str]) -> Vec<String> {
        args.iter().map(|arg| arg.to_string()).collect()
    }

    #[test]
    fn an_alias_is_replaced_where_it_stands() {
        let (args, warnings) = expand_aliases(&strings(&[
            "-O2",
            "-mfused-madd",
            "-msse5",
            "x.c",
            "-mno-sse5",
        ]))
        .unwrap();
        assert_eq!(
            args,
            ["-O2", "-ffp-contract=fast", "-mavx", "x.c", "-mno-avx"]
        );
        assert_eq!(
            warnings,
            [
                "'-mfused-madd' is deprecated; use '-ffp-contract=' instead",
                "'-msse5' was removed"
            ]
        );
        let (args, warnings) = expand_aliases(&strings(&[
            "-mno-fused-madd",
            "-mno-intel-syntax",
            "-mintel-syntax",
            "-mstore-max=256",
        ]))
        .unwrap();
        assert_eq!(
            args,
            [
                "-ffp-contract=off",
                "-masm=att",
                "-masm=intel",
                "-mmove-max=256"
            ]
        );
        assert_eq!(warnings.len(), 3);
        assert_eq!(
            warnings[2],
            "'-mstore-max=' is deprecated; use '-mmove-max=' instead"
        );
    }

    #[test]
    fn a_command_line_without_aliases_is_unchanged() {
        let args = strings(&["-O2", "-mavx2", "-malign-data=abi", "-mmove-max=128", "x.c"]);
        assert_eq!(expand_aliases(&args).unwrap(), (args, vec![]));
    }

    /// GCC 16.2: `-malign-functions=5` is `-falign-functions=32` unless
    /// an `-falign-functions` is given, before it or behind it.
    #[test]
    fn an_obsolete_alignment_yields_to_an_explicit_one() {
        let (args, warnings) = expand_aliases(&strings(&[
            "-falign-functions=64",
            "-malign-functions=5",
            "-malign-loops=4",
            "-malign-jumps=0",
            "x.c",
        ]))
        .unwrap();
        assert_eq!(
            args,
            [
                "-falign-functions=32",
                "-falign-loops=16",
                "-falign-functions=64",
                "x.c"
            ]
        );
        assert_eq!(
            warnings,
            [
                "'-malign-functions' is obsolete, use '-falign-functions'",
                "'-malign-loops' is obsolete, use '-falign-loops'",
                "'-malign-jumps' is obsolete, use '-falign-jumps'"
            ]
        );
        assert_eq!(
            expand_aliases(&strings(&["-malign-functions=17"])).unwrap_err(),
            "'-malign-functions=17' is not between 0 and 16"
        );
        assert_eq!(
            expand_aliases(&strings(&["-malign-loops=x"])).unwrap_err(),
            "argument to '-malign-loops=' should be a non-negative integer"
        );
        assert_eq!(
            expand_aliases(&strings(&["-malign-jumps="])).unwrap_err(),
            "missing argument to '-malign-jumps='"
        );
        // Not one of the three: left for the argument loop.
        let other = strings(&["-malign-data=abi", "-malign-labels=4"]);
        assert_eq!(expand_aliases(&other).unwrap().0, other);
    }
