//! GNU as 2.47 ground truth for the Advanced-SIMD and FP forms added or
//! corrected with the FP16 / Advanced-SIMD scalar / FHM / FCMA / BF16 /
//! DotProd / I8MM / RDM / crypto coverage work, assembled through the full
//! parser -> dispatcher -> leaf path.
//!
//! `GAS247_WORDS` is every audited instruction that the previous assembler
//! mis-encoded (19: vector `fneg`/`fmulx`, register post-index single-lane
//! `ld1`..`st4`) or rejected (367 measured, e.g. `movi d0, #0`, `ushr d0,
//! d0, #32`, `fmov v0.4s, #1.0`, `fccmp`, `sdot`, `sha256h`); each word is
//! GAS's (`.arch armv9.4-a+sme+aes+sha3+sm4`).  `GAS247_REJECTS` is every
//! audited spelling GAS refuses that the previous assembler accepted --
//! mostly into the word of another instruction (`and v0.4h, ...` assembled
//! as BIC, `ld1 {v3.16b}, [x5], #8` advanced the pointer by 16).  Both lists
//! were generated by assembling each line with GAS and LCCC and keeping the
//! cells whose verdict changed; regenerate them the same way when a form is
//! added (see `scripts/gen_aarch64_dispatcher_goldens.py` for the oracle
//! set-up).

use super::*;
use crate::backend::arm::assembler::parser::{AsmStatement, parse_asm};

fn assemble_one(text: &str) -> Result<u32, String> {
    let stmts = parse_asm(text).map_err(|e| format!("parse: {e}"))?;
    let mut words = Vec::new();
    for st in &stmts {
        if let AsmStatement::Instruction {
            mnemonic,
            operands,
            raw_operands,
        } = st
        {
            match encode_instruction(mnemonic, operands, raw_operands)? {
                EncodeResult::Word(w) => words.push(w),
                other => return Err(format!("unexpected encode result {other:?}")),
            }
        }
    }
    match words.as_slice() {
        [w] => Ok(*w),
        _ => Err(format!(
            "expected one instruction word, got {}",
            words.len()
        )),
    }
}

#[test]
fn advsimd_and_fp_forms_match_gas247() {
    let mut bad = Vec::new();
    for &(text, want) in GAS247_WORDS {
        match assemble_one(text) {
            Ok(got) if got == want => {}
            Ok(got) => bad.push(format!("{text}: got {got:#010x}, GAS {want:#010x}")),
            Err(e) => bad.push(format!("{text}: rejected ({e}), GAS {want:#010x}")),
        }
    }
    assert!(
        bad.is_empty(),
        "{} of {} forms disagree with GNU as 2.47:\n{}",
        bad.len(),
        GAS247_WORDS.len(),
        bad.join("\n")
    );
}

#[test]
fn advsimd_and_fp_spellings_gas247_rejects_are_rejected() {
    let accepted: Vec<String> = GAS247_REJECTS
        .iter()
        .filter_map(|text| {
            assemble_one(text)
                .ok()
                .map(|w| format!("{text} -> {w:#010x}"))
        })
        .collect();
    assert!(
        accepted.is_empty(),
        "{} spellings GNU as 2.47 rejects were assembled:\n{}",
        accepted.len(),
        accepted.join("\n")
    );
}

