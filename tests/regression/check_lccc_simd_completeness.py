#!/usr/bin/env python3
"""Link-level completeness gate for the `__lccc_simd*` intrinsic surface.

WHY THIS EXISTS
---------------
`include/lcccsimd.h` declares every SIMD intrinsic LCCC offers, and lowering
resolves those declarations through exactly two hand-written tables:

  * the mnemonic table in `src/ir/lowering/expr_builtins_lcccsimd.rs`, and
  * the emitter tables in `src/backend/x86/codegen/intrinsics_simd.rs`.

Both are flat `match` arms, one line per op. A symbol that the header
advertises but either table does not know cannot be lowered, so the call
survives to the linker as an external reference and *every translation unit
that uses that intrinsic fails to link* -- a whole-program failure caused by a
one-line omission, invisible to any test that only executes code.

That is not a thought experiment. `_mm_cvtsd_si32` lost its table entry and its
emitter arm in a merge-conflict resolution; the compiler still built cleanly,
5744 unit tests still passed, and the failure only appeared as
`undefined reference to '__lccc_simd128_ps_cvtsd2si128'` in CI. The static
completeness test in `expr_builtins_lcccsimd.rs` covers the mnemonic table; this
gate covers the whole path by *compiling and linking* a call to every declared
symbol, which is the property users actually depend on.

WHAT IT PROVES
--------------
Every `__lccc_simd{128,256,512}_{class}_{mnemonic}` symbol declared in the
generated header is accepted by the front end, lowered, and does not escape to
the linker. One TU exercises the entire surface, so the cost is one compile and
one link regardless of how many intrinsics exist.

The gate is host-independent: it needs only the compiler under test and a C
driver for linking, both already requirements of every other gate. It fails
closed -- an unparseable declaration, an unbuildable TU, or a parse that yields
an implausible symbol count is an error, never a skip.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
HEADER = ROOT / "include" / "lcccsimd.h"

# `__m512i __lccc_simd512_i_vpaddd512(long, __m512i __a, __m512i __b);`
DECL = re.compile(
    r"^(?P<ret>[A-Za-z_][A-Za-z0-9_ ]*?)\s*"
    r"(?P<sym>__lccc_simd(?:128|256|512)_[a-z]+_[A-Za-z0-9_]+)\s*"
    r"\((?P<params>[^;]*)\)\s*;",
    re.M,
)

# Vector and integer types the surface uses. A parameter of any other type is a
# declaration this gate does not understand, and must fail loudly rather than
# be silently dropped -- dropping it would recreate the blind spot the gate
# exists to close.
SCALAR_ZERO = {"long": "0", "int": "0", "unsigned": "0u", "unsigned long": "0ul"}

# `void`-flavoured parameters are pointer slots (a null pointer is a valid
# argument for every one of them), so they take a literal rather than a static.
POINTER_PARAMS = {"void", "const void", "void *", "const void *"}


def parse_surface(text):
    """-> list of (symbol, return type, [(param type, param name)])."""
    surface = []
    for match in DECL.finditer(text):
        ret = " ".join(match.group("ret").split())
        params = []
        for raw in match.group("params").split(","):
            parts = raw.split()
            if not parts:
                raise ValueError(f"{match.group('sym')}: empty parameter")
            if len(parts) == 1:
                # The dummy/immediate slot is declared without a name.
                params.append((parts[0], f"__unnamed{len(params)}"))
            else:
                params.append((" ".join(parts[:-1]), parts[-1]))
        surface.append((match.group("sym"), ret, params))
    return surface


def build_source(surface):
    """One function per symbol: it must lower, not merely type-check."""
    # Vector types are aggregates in LCCC (`__m512i` is a struct), so they are
    # zero-initialised at file scope rather than by `= 0`. Scalars used for the
    # dummy/immediate slot pass a literal.
    vectors = []
    for _symbol, _ret, params in surface:
        for ptype, _pname in params:
            if ptype in POINTER_PARAMS:
                continue
            if ptype not in SCALAR_ZERO and ptype not in vectors:
                vectors.append(ptype)
    lines = [
        "/* generated by tests/regression/check_lccc_simd_completeness.py */",
        "#include <lcccsimd.h>",
        "",
    ]
    for ptype in vectors:
        lines.append(f"static {ptype} z_{ptype.replace(' ', '_')};")
    lines.append("")
    for symbol, ret, params in surface:
        lines.append(f"void use_{symbol}(void)")
        lines.append("{")
        args = ", ".join(
            SCALAR_ZERO[ptype] if ptype in SCALAR_ZERO
            else "0" if ptype in POINTER_PARAMS
            else f"z_{ptype.replace(' ', '_')}"
            for ptype, _ in params
        )
        if ret == "void":
            lines.append(f"    {symbol}({args});")
        else:
            lines.append(f"    {ret} r = {symbol}({args});")
            lines.append("    (void)r;")
        lines.append("}")
        lines.append("")
    # A full executable link is the point: it surfaces any symbol the lowering
    # never emitted as an undefined reference.
    lines.append("int main(void)")
    lines.append("{")
    lines.append("    return 0;")
    lines.append("}")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--compiler", default=str(ROOT / "target/fastbuild/lccc"))
    ap.add_argument("--keep", action="store_true", help="keep the generated TU")
    args = ap.parse_args()

    surface = parse_surface(HEADER.read_text())
    symbols = [s for s, _, _ in surface]
    if len(symbols) < 250:
        raise SystemExit(
            f"completeness gate: parsed only {len(symbols)} declarations from "
            f"{HEADER}; the parser or the header is broken"
        )
    # The header deliberately repeats a prototype above each macro that uses
    # it, so identical redeclarations are expected. A *conflicting* one would
    # be a real defect: two wrappers would disagree about the ABI of the same
    # symbol. Compare signatures rather than counting names.
    signatures = {}
    conflicts = []
    for symbol, ret, params in surface:
        signature = (ret, tuple(t for t, _ in params))
        if signatures.setdefault(symbol, signature) != signature:
            conflicts.append((symbol, signatures[symbol], signature))
    if conflicts:
        detail = "\n".join(f"  {s}: {a} vs {b}" for s, a, b in conflicts)
        raise SystemExit(f"completeness gate: conflicting redeclarations:\n{detail}")
    surface = [(symbol, ret, params) for symbol, ret, params in surface
               if signatures[symbol] == (ret, tuple(t for t, _ in params))]
    deduped = {}
    for symbol, ret, params in surface:
        deduped.setdefault(symbol, (symbol, ret, params))
    surface = [deduped[name] for name in sorted(deduped)]

    workdir = pathlib.Path(tempfile.mkdtemp(prefix="lccc-simd-completeness-"))
    source = workdir / "surface.c"
    source.write_text(build_source(surface))
    objects = workdir / "surface.o"

    compile_result = subprocess.run(
        [args.compiler, "-O2", "-c", str(source), "-o", str(objects)],
        text=True,
        capture_output=True,
    )
    if compile_result.returncode != 0:
        print(compile_result.stdout[-4000:], file=sys.stderr)
        print(compile_result.stderr[-4000:], file=sys.stderr)
        raise SystemExit(
            "completeness gate: the declared intrinsic surface does not compile"
        )

    # Undefined references are the point of the gate: they name the exact
    # symbols that have no lowering.
    link_result = subprocess.run(
        [args.compiler, str(objects), "-o", workdir / "surface"],
        text=True,
        capture_output=True,
    )
    if link_result.returncode != 0:
        undefined = sorted(set(re.findall(r"undefined reference to [`']([^'\"]+)", link_result.stderr)))
        print(link_result.stderr[-4000:], file=sys.stderr)
        detail = "\n".join(f"  {name}" for name in undefined) or "  (see linker output)"
        raise SystemExit(
            f"completeness gate: {len(undefined)} declared intrinsic(s) do not "
            f"lower and would break every user of them:\n{detail}"
        )

    if args.keep:
        print(f"kept: {source}")
    print(
        f"intrinsic surface: PASS ({len(surface)} declared symbols lower and link)"
    )


if __name__ == "__main__":
    main()
