#!/usr/bin/env python3
"""Emit a self-checking C program that sweeps __seg_gs aggregate copies.

Every size in SIZES gets its own struct type and its own __seg_gs object, so
the straight-line copy (<= SEG_COPY_UNROLL_MAX), the counted loop above it, and
the tail after the loop are all exercised at every boundary that matters:

  * sizes 1..=600 (every straight-line length, each tail width 1..7),
  * 511, 512, 513 (the unroll limit), 1000, 1023, 1024, 1025 (loop tails),
    2048, 4095, 4096, 4097, 5000 (multi-page loops).

Each object sits in a guarded __seg_gs wrapper: the bytes after the copied
object are a guard pattern that a copy of the wrong length would overwrite.

Per size and per round (three rounds, each with a new byte pattern):

  1. generic -> segment copy, then the mirror (&object + GS_DISP) is compared
     with the source bytes;
  2. segment -> generic copy, compared with the source;
  3. segment -> segment copy into a second object, compared through its mirror;
  4. the guard bytes after each object are unchanged.

The program prints one `ok`/`FAIL` line per size and a final PASSED line. The
gate runs it under lccc and under GCC -O0 and requires identical output, GCC
being the oracle for accepted behaviour.

usage: gen_seg_copy_sweep.py OUT.c [--full]

Without --full the program covers FAST_SIZES (192 sizes, bounded compile time
for the fast gate). --full covers FULL_SIZES (609 sizes: every length 1..=600
plus the loop edges).
"""
import sys

# The loop copies 32-byte blocks, so 513..=544 holds every residue modulo 32
# (the loop-count and tail combinations of the first trip) above the limit.
LOOP_EDGES = ([511, 512] + list(range(513, 545)) +
              [1000, 1023, 1024, 1025, 2047, 2048, 2049, 4095, 4096, 4097, 5000])
# Fast set (default, used by the gate): every length 1..=64, residues 1, 8 and
# 15 modulo 16 up to 512 (the straight-line limit), and the loop edges above.
FAST_SIZES = sorted(set(range(1, 65))
                    | {n for n in range(65, 513) if n % 16 in (1, 8, 15)}
                    | set(LOOP_EDGES))
# Full set (--full): every length 1..=600 and the same loop edges.
FULL_SIZES = sorted(set(range(1, 601)) | set(LOOP_EDGES))
SIZES = FAST_SIZES
ROUNDS = 3
GUARD = 16


def emit(sizes) -> str:
    global SIZES
    SIZES = sizes
    out = []
    w = out.append
    w("/* Generated by gen_seg_copy_sweep.py. Do not edit. */")
    w("#include <errno.h>")
    w("#include <stdint.h>")
    w("#include <stdio.h>")
    w("#include <stdlib.h>")
    w("#include <string.h>")
    w("#include <sys/mman.h>")
    w("#include <sys/syscall.h>")
    w("#include <unistd.h>")
    w("")
    w("#define ARCH_SET_GS 0x1001")
    w("#define GS_DISP ((uintptr_t)1 << 32)")
    w("#define MIR(g) ((unsigned char *)(g) + GS_DISP)")
    w("")
    for n in SIZES:
        w(f"struct s{n} {{ unsigned char b[{n}]; }};")
        w(f"struct w{n} {{ struct s{n} o; unsigned char g[{GUARD}]; }};")
        w(f"struct w{n} __seg_gs seg{n};")
        w(f"struct w{n} __seg_gs seg2_{n};")
    w("")
    w("static void fill(unsigned char *p, size_t n, unsigned seed) {")
    w("    for (size_t i = 0; i < n; i++)")
    w("        p[i] = (unsigned char)(i * 131u + seed * 7u + 3u);")
    w("}")
    w("")
    w("static int bad_bytes(const unsigned char *a, const unsigned char *b, size_t n) {")
    w("    for (size_t i = 0; i < n; i++)")
    w("        if (a[i] != b[i]) return 1;")
    w("    return 0;")
    w("}")
    w("")
    w("static int guard_ok(const unsigned char *g) {")
    w(f"    for (int i = 0; i < {GUARD}; i++)")
    w("        if (g[i] != 0xA5) return 0;")
    w("    return 1;")
    w("}")
    w("")
    w("/* Maps the mirror (object + GS_DISP) of one segment object. Runs before any")
    w("   write, so MAP_FIXED over a page shared with a neighbour loses no data. */")
    w("static void map_obj(const void *g, size_t n) {")
    w("    uintptr_t lo = (uintptr_t)g + GS_DISP;")
    w("    uintptr_t page = lo & ~(uintptr_t)4095;")
    w("    size_t len = ((lo + n - page) + 4095) & ~(size_t)4095;")
    w("    void *m = mmap((void *)page, len, PROT_READ | PROT_WRITE,")
    w("                   MAP_PRIVATE | MAP_ANONYMOUS | MAP_FIXED, -1, 0);")
    w("    if (m == MAP_FAILED) { perror(\"mmap mirror\"); exit(2); }")
    w("}")
    w("")
    w("static void reset_guards(void) {")
    for n in SIZES:
        w(f"    memset(MIR(&seg{n}.g), 0xA5, {GUARD});")
        w(f"    memset(MIR(&seg2_{n}.g), 0xA5, {GUARD});")
    w("}")
    w("")
    # One checking function per size. The copies are written out in full so
    # each one is a distinct, inlined-or-not aggregate copy in the code.
    for n in SIZES:
        w(f"static int check{n}(void) {{")
        w(f"    struct s{n} src, back;")
        w("    int bad = 0;")
        w(f"    for (unsigned r = 0; r < {ROUNDS}; r++) {{")
        w(f"        fill(src.b, {n}, r * 17u + {n}u);")
        w(f"        seg{n}.o = src;")
        w(f"        if (bad_bytes(MIR(&seg{n}.o), src.b, {n})) bad |= 1;")
        w(f"        back = seg{n}.o;")
        w(f"        if (bad_bytes(back.b, src.b, {n})) bad |= 2;")
        w(f"        seg2_{n}.o = seg{n}.o;")
        w(f"        if (bad_bytes(MIR(&seg2_{n}.o), src.b, {n})) bad |= 4;")
        w(f"        if (!guard_ok(MIR(&seg{n}.g)) || !guard_ok(MIR(&seg2_{n}.g))) bad |= 8;")
        w("    }")
        w("    return bad;")
        w("}")
        w("")
    w("int main(void) {")
    w("    /* Map every object's mirror, then fill the guards. */")
    for n in SIZES:
        w(f"    map_obj((const char *)&seg{n}, sizeof seg{n});")
        w(f"    map_obj((const char *)&seg2_{n}, sizeof seg2_{n});")
    w("    if (syscall(SYS_arch_prctl, ARCH_SET_GS, (unsigned long)GS_DISP) != 0) {")
    w("        perror(\"arch_prctl\");")
    w("        return 2;")
    w("    }")
    w("    reset_guards();")
    w("    int failures = 0;")
    for n in SIZES:
        w(f"    if (check{n}() == 0) printf(\"ok %d\\n\", {n}); else {{ printf(\"FAIL %d\\n\", {n}); failures++; }}")
    w(f"    if (failures == 0) printf(\"seg_copy_sweep PASSED ({len(SIZES)} sizes)\\n\");")
    w("    else printf(\"seg_copy_sweep FAILED (%d sizes)\\n\", failures);")
    w("    return failures == 0 ? 0 : 1;")
    w("}")
    return "\n".join(out) + "\n"


def main() -> int:
    args = sys.argv[1:]
    full = "--full" in args
    args = [a for a in args if a != "--full"]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    with open(args[0], "w", encoding="utf-8") as f:
        f.write(emit(FULL_SIZES if full else FAST_SIZES))
    return 0


if __name__ == "__main__":
    sys.exit(main())
