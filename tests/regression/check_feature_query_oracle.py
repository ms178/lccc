#!/usr/bin/env python3
"""Differential gate: `__has_feature` / `__has_extension` vs the GCC 16.2 oracle.

The oracle matrix in
``engineering/evidence/2026-11-08-rucc-audit/feature-query-oracle.json``
was measured on GCC 16.2.0 and Clang 23.1.5 (21 names x 18 modes).  This gate
replays every GCC mode against LCCC and asserts the *truthfulness contract*:

* a capability LCCC implements answers exactly what GCC 16.2 answers;
* a capability LCCC does not implement answers 0 in every mode, even when GCC
  answers 1 — a false claim is worse than a conservative one, because headers
  use the answer to select code paths the front end must then honor;
* the ``#if`` path and the ordinary-code path agree with each other.

LCCC follows its GCC persona, not Clang's: GCC macro-expands the operand and
treats C23 binary literals as a feature, Clang does neither.

Sanitizer modes need a translation: LCCC implements UBSan in trap mode only
(no libubsan runtime), so ``-fsanitize=undefined`` is replayed with
``-fsanitize-trap=all``.  AddressSanitizer is not implemented at all, so the
driver must *reject* ``-fsanitize=address`` rather than pretend; that rejection
is asserted instead of a query value.

No oracle compiler is needed at run time: the measured answers are committed.
"""
from __future__ import annotations

import argparse
import json
import re
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
DEFAULT_ORACLE = ROOT / "engineering/evidence/2026-11-08-rucc-audit/feature-query-oracle.json"

# Capabilities LCCC implements end to end.  Everything else in the oracle must
# answer 0.  Keep this list in sync with src/frontend/preprocessor/feature_queries.rs;
# the Rust unit test `every_implemented_row_is_reachable` pins the other side.
IMPLEMENTED = {
    "c_alignas",
    "c_alignof",
    # c_atomic / __c_atomic__ are deliberately NOT here: `_Atomic` is parsed
    # but its RMW and seq_cst store semantics are not lowered (measured
    # miscompiles), so the truthful answer is 0 even though GCC answers 1.
    "c_generic_selections",
    "c_static_assert",
    "c_thread_local",
    "cxx_binary_literals",
    "tls",
    "undefined_behavior_sanitizer",
    "gnu_asm_goto_with_outputs",
    "gnu_asm_goto_with_outputs_full",
}

# Modes whose sanitizer LCCC does not implement: the driver must reject them.
REJECTED_MODES = {"-fsanitize=address", "-fsanitize=kernel-address"}

DECL = re.compile(r"int\s+(ifhf|ifhe|hf|he)_(\w+)\s*=\s*(\d+)\s*;")


def names_from_oracle(matrix: dict) -> list[str]:
    names = set()
    for modes in matrix.values():
        for rows in modes.values():
            for key in rows:
                if key.startswith(("hf_", "he_")):
                    names.add(key[3:])
    return sorted(names)


def make_source(names: list[str]) -> str:
    lines = ["/* Generated by check_feature_query_oracle.py — do not edit. */"]
    for name in names:
        lines.append(f"int hf_{name} = __has_feature({name});")
        lines.append(f"int he_{name} = __has_extension({name});")
    for name in names:
        lines.append(f"#if __has_feature({name})")
        lines.append(f"int ifhf_{name} = 1;")
        lines.append("#else")
        lines.append(f"int ifhf_{name} = 0;")
        lines.append("#endif")
        lines.append(f"#if __has_extension({name})")
        lines.append(f"int ifhe_{name} = 1;")
        lines.append("#else")
        lines.append(f"int ifhe_{name} = 0;")
        lines.append("#endif")
    return "\n".join(lines) + "\n"


def run(ccc: str, source: Path, flags: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(
        [ccc, "-E", *flags, str(source)],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        timeout=120,
    )


def parse(text: str) -> dict[str, int]:
    out = {}
    for kind, name, value in DECL.findall(text):
        out[f"{kind}_{name}"] = int(value)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lccc", default=str(ROOT / "target/fastbuild/lccc"))
    ap.add_argument("--oracle", type=Path, default=DEFAULT_ORACLE)
    ap.add_argument("--persona", default="gcc-16", help="oracle key to replay (GCC persona)")
    args = ap.parse_args(argv)

    matrix = json.loads(args.oracle.read_text())
    if args.persona not in matrix:
        print(f"error: persona {args.persona!r} not in oracle (have {sorted(matrix)})", file=sys.stderr)
        return 2
    modes = matrix[args.persona]
    names = names_from_oracle({args.persona: modes})
    if not names:
        print("error: oracle has no feature names", file=sys.stderr)
        return 2

    failures: list[str] = []
    checks = 0
    with tempfile.TemporaryDirectory(prefix="lccc-feature-oracle.") as tmp:
        source = Path(tmp) / "features.c"
        source.write_text(make_source(names))
        for mode, expected in modes.items():
            flags = shlex.split(mode)
            if mode in REJECTED_MODES:
                proc = run(args.lccc, source, flags)
                checks += 1
                if proc.returncode == 0:
                    failures.append(
                        f"{mode}: LCCC accepted an unimplemented sanitizer; it must reject it"
                    )
                continue
            # LCCC implements UBSan in trap mode only; replay the GCC mode with
            # the trap flag that makes the same checks active.
            if any(f.startswith("-fsanitize=") for f in flags):
                flags = [*flags, "-fsanitize-trap=all"]
            proc = run(args.lccc, source, flags)
            if proc.returncode != 0:
                failures.append(f"{mode}: lccc -E failed: {proc.stderr.strip()[:400]}")
                continue
            got = parse(proc.stdout)
            for name in names:
                for op in ("hf", "he"):
                    key = f"{op}_{name}"
                    if key not in expected:
                        continue
                    want = expected[key] if name in IMPLEMENTED else 0
                    checks += 1
                    if key not in got:
                        failures.append(f"{mode}: missing {key} in -E output")
                        continue
                    if got[key] != want:
                        why = "GCC parity" if name in IMPLEMENTED else "truthful zero"
                        failures.append(
                            f"{mode}: {key} = {got[key]}, want {want} ({why})"
                        )
                    # The #if path must agree with the code-line path.
                    ifkey = f"if{op}_{name}"
                    checks += 1
                    if ifkey not in got:
                        failures.append(f"{mode}: missing {ifkey} in -E output")
                    elif got[ifkey] != got[key]:
                        failures.append(
                            f"{mode}: {ifkey} = {got[ifkey]} but {key} = {got[key]} "
                            "(#if and code-line paths disagree)"
                        )

    if failures:
        print(f"FAIL: feature-query oracle ({len(failures)} of {checks} checks)", file=sys.stderr)
        for line in failures[:80]:
            print(f"  {line}", file=sys.stderr)
        if len(failures) > 80:
            print(f"  ... and {len(failures) - 80} more", file=sys.stderr)
        return 1
    print(f"feature-query oracle: ok ({checks} checks, {len(modes)} modes, {len(names)} names)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
