#!/usr/bin/env python3
"""Deterministic legacy SSE3/SSSE3/SSE4 matrix (not AVX aliases).

Instruction inventory: Intel XED datafiles/xed-isa.txt, Intel SDM 093
instruction entries; AMD APM Vol.4 26568 rev3.27 for SSE4a. These are encoding
probes, never a claim that unsafe system/non-temporal ops were executed.
"""
from pathlib import Path

SSE3 = 'addsubpd addsubps haddpd haddps hsubpd hsubps movddup movshdup movsldup'.split()
SSSE3 = 'pabsb pabsw pabsd phaddw phaddd phaddsw phsubw phsubd phsubsw pmaddubsw pmulhrsw pshufb psignb psignw psignd'.split()
SSE41 = ('packusdw pcmpeqq phminposuw pmaxsb pmaxsd pmaxuw pmaxud pminsb pminsd pminuw pminud '
         'pmovsxbw pmovsxbd pmovsxbq pmovsxwd pmovsxwq pmovsxdq pmovzxbw pmovzxbd pmovzxbq pmovzxwd pmovzxwq pmovzxdq pmuldq pmulld ptest').split()
IMM = 'palignr blendpd blendps dppd dpps insertps mpsadbw pblendw roundpd roundps roundsd roundss pcmpestri pcmpestrm pcmpistri pcmpistrm'.split()
LOAD = ['lddqu', 'movntdqa']
BLEND = ['blendvpd', 'blendvps', 'pblendvb']


def generate(bits):
    out = ['# Generated by tests/asm-diff/gen_sse34.py; do not edit.\n']
    def case(name, lines, reject=False):
        out.append(';;; ' + name + (' reject' if reject else '') + '\n.text\n' + '\n'.join(lines) + '\n')
    n = 16 if bits == 64 else 8
    ptr = 'rax' if bits == 64 else 'eax'
    idx = 'rcx' if bits == 64 else 'ecx'
    mems = [f'{d}(%{ptr},%{idx},4)' for d in (-129,-128,0,127,128,4096)]
    if bits == 64:
        mems += ['(%r13,%r14,8)', '128(%rip)', '(%rsp)', '(%rbp)']
    else:
        mems += ['(%esp)', '(%ebp)', '128(%bx,%si)']
    for m in SSE3 + SSSE3 + SSE41 + ['pcmpgtq']:
        lines = [f'{m} %xmm{i},%xmm{j}' for i in range(n) for j in range(n)]
        lines += [f'{m} {a},%xmm{j}' for a in mems for j in (0,n-1)]
        if m in SSSE3:
            lines += [f'{m} %mm{i},%mm{j}' for i in range(8) for j in range(8)]
            lines += [f'{m} {a},%mm7' for a in mems]
            case(m+'_mixed', [f'{m} %mm0,%xmm0'], True)
        else:
            case(m+'_no_mmx', [f'{m} %mm0,%mm1'], True)
        case(m, lines)
        case(m+'_no_gp', [f'{m} %eax,%xmm0'], True)
        case(m+'_no_wide', [f'{m} %ymm0,%ymm1'], True)
        case(m+'_no_store', [f'{m} %xmm0,(%{ptr})'], True)
    for m in IMM:
        lines = [f'{m} ${v},%xmm{n-1},%xmm0' for v in range(256)]
        lines += [f'{m} $129,{a},%xmm{n-1}' for a in mems]
        if m == 'palignr': lines += [f'{m} ${v},%mm7,%mm0' for v in range(256)]
        case(m, lines)
        case(m+'_no_wide', [f'{m} $1,%ymm0,%ymm1'], True)
        case(m+'_overflow', [f'{m} $256,%xmm0,%xmm1'], True)
    for m in LOAD:
        case(m, [f'{m} {a},%xmm{i}' for a in mems for i in (0,n-1)])
        case(m+'_memory_only', [f'{m} %xmm1,%xmm0'], True)
    for m in BLEND:
        case(m, [f'{m} %xmm0,%xmm{i},%xmm{j}' for i in range(n) for j in range(n)]
             + [f'{m} %xmm0,{a},%xmm{n-1}' for a in mems])
        case(m+'_bad_mask', [f'{m} %xmm1,%xmm2,%xmm3'], True)
    for m in ('movntsd','movntss'):
        case(m, [f'{m} %xmm{i},{a}' for a in mems for i in (0,n-1)])
        case(m+'_store_only', [f'{m} (%{ptr}),%xmm0'], True)
        case(m+'_no_mmx', [f'{m} %mm0,(%{ptr})'], True)
    for m in ('extrq','insertq'):
        case(m, [f'{m} %xmm{i},%xmm{j}' for i in range(n) for j in range(n)])
        regs = f'%xmm{n-1}' if m == 'extrq' else f'%xmm0,%xmm{n-1}'
        case(m+'_controls', [f'{m} ${v},$17,{regs}' for v in range(256)]
             + [f'{m} $19,${v},{regs}' for v in range(256)])
        case(m+'_no_memory', [f'{m} (%{ptr}),%xmm1'], True)
    for m in ('pextrb','pextrw','pextrd','extractps') + (('pextrq',) if bits==64 else ()):
        reg = 'rax' if m == 'pextrq' else 'eax'
        case(m, [f'{m} ${v},%xmm{n-1},%{reg}' for v in range(256)]
             + [f'{m} $3,%xmm{n-1},{a}' for a in mems])
    for m in ('pinsrb','pinsrd') + (('pinsrq',) if bits==64 else ()):
        reg = 'rax' if m=='pinsrq' else 'eax'
        case(m, [f'{m} ${v},%{reg},%xmm{n-1}' for v in range(256)]
             + [f'{m} $3,{a},%xmm{n-1}' for a in mems])
    for m in ('fisttps','fisttpl','fisttpq'):
        case(m, [f'{m} {a}' for a in mems])
    case('monitor_mwait', ['monitor','mwait'])
    for suf,reg in [('b','al'),('w','ax'),('l','eax')] + ([('q','rax')] if bits==64 else []):
        dst = 'rdx' if suf=='q' else 'edx'
        case('crc32'+suf, [f'crc32{suf} %{reg},%{dst}']+[f'crc32{suf} {a},%{dst}' for a in mems])
    for text in ('crc32w %ax,%edx', 'crc32 %eax,%edx'):
        case('crc_alias_'+str(len(out)), [text])
    for text in ('crc32b %xmm0,%eax','crc32w %eax,%edx','crc32l %eax,%dx'):
        case('crc_bad_'+str(len(out)), [text], True)
    if bits == 64:
        case('crc_high_byte', ['crc32b %ah,%eax', 'crc32b %sil,%r9d', 'crc32b %r9b,%r10', 'crc32b %al,%rax'])
        for text in ('crc32w %ax,%rax','crc32l %eax,%rax','crc32b %ah,%r9d','crc32b %ah,%rax'):
            case('crc_bad64_'+str(len(out)), [text], True)
    for m in ('extrq','insertq'):
        reg = '%xmm0' if m == 'extrq' else '%xmm0,%xmm1'
        case(m+'_overflow', [f'{m} $256,$1,{reg}'], True)
    for suf,reg in [('w','ax'),('l','eax')] + ([('q','rax')] if bits==64 else []):
        dst = 'dx' if suf=='w' else ('rdx' if suf=='q' else 'edx')
        case('popcnt'+suf, [f'popcnt{suf} %{reg},%{dst}']+[f'popcnt{suf} {a},%{dst}' for a in mems])
    return '\n'.join(out)

if __name__ == '__main__':
    root = Path(__file__).parent
    for bits, path in [(64,root/'sse34-complete.casefile'), (32,root/'i686/sse34-complete.casefile')]:
        path.write_text(generate(bits))
