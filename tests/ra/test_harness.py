#!/usr/bin/env python3
"""Determinism, assembly-parser and checksum tests for the RA research harness."""
from __future__ import annotations

import argparse
import importlib.util
import shutil
import signal
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def load_module(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--full", action="store_true", help="check GCC O0/O1/O2/O3 (slower)")
    args = parser.parse_args()
    if not shutil.which("gcc"):
        print("ERROR: gcc is required for the RA harness checksum gate", file=sys.stderr)
        return 2

    with tempfile.TemporaryDirectory(prefix="lccc-ra-harness-test-") as td:
        root = Path(td)
        a, b = root / "a", root / "b"
        subprocess.run([sys.executable, str(ROOT / "tests/ra/gen_rastress.py"), "--output-dir", str(a)], check=True, capture_output=True)
        subprocess.run([sys.executable, str(ROOT / "tests/ra/gen_rastress.py"), "--output-dir", str(b)], check=True, capture_output=True)
        files_a = sorted(a.glob("*.c"))
        files_b = sorted(b.glob("*.c"))
        assert len(files_a) == 20, f"expected 20 holdout kernels, got {len(files_a)}"
        assert [p.name for p in files_a] == [p.name for p in files_b]
        for x, y in zip(files_a, files_b):
            assert x.read_bytes() == y.read_bytes(), f"non-deterministic generated source: {x.name}"

        stale_dir = root / "stale"
        stale_dir.mkdir()
        (stale_dir / "old_kernel.c").write_text("/* Generated by tests/ra/gen_rastress.py; do not edit. */\n")
        custom_source = stale_dir / "custom.c"
        custom_source.write_text("/* user-owned */\nint custom;\n")
        subprocess.run([sys.executable, str(ROOT / "tests/ra/gen_rastress.py"), "--output-dir", str(stale_dir)], check=True, capture_output=True)
        assert not (stale_dir / "old_kernel.c").exists(), "stale generated C file was retained"
        assert custom_source.read_text() == "/* user-owned */\nint custom;\n", "generator modified user-owned source"
        conflict_dir = root / "conflict"
        conflict_dir.mkdir()
        stale_conflict = conflict_dir / "old_kernel.c"
        stale_conflict.write_text("/* Generated by tests/ra/gen_rastress.py; do not edit. */\n")
        conflict = conflict_dir / "bitdecode.c"
        conflict.write_text("/* user-owned conflict */\n")
        refused = subprocess.run([sys.executable, str(ROOT / "tests/ra/gen_rastress.py"), "--output-dir", str(conflict_dir)], capture_output=True, text=True)
        assert refused.returncode != 0 and "refusing to overwrite" in refused.stderr
        assert conflict.read_text() == "/* user-owned conflict */\n"
        assert stale_conflict.exists(), "failed preflight modified the existing corpus"

        scorer = load_module("ra_spill_compare", ROOT / "tests/ra/spill_compare.py")
        assembly = """.type f,@function
f:
    pushq %rbx
.Lloop:
    movq -8(%rsp), %rax
    pushq %rax
    popq %rax
    addq $1, %rdi
    jne .Lloop
    popq %rbx
    ret
.size f,.-f
"""
        counts = scorer.instruction_counts(scorer.assembly_functions(assembly)["f"])
        assert counts["stack_operands"] == 1, counts
        assert counts["push"] == 2 and counts["pop"] == 2, counts
        assert counts["loop_push_pop"] == 2, counts

        section_asm = """.type f,@function
.text
f:
    .pushsection .rodata
held_data:
    .quad 7
    .popsection
    ret
.size f,.-f
.data
data_object:
    .quad 9
.text
.type g,@function
g:
    ret
.size g,.-g
"""
        section_functions = scorer.assembly_functions(section_asm)
        assert set(section_functions) == {"f", "g"}, section_functions
        assert scorer.split_operands("%rax, 8(%rsp,%rcx,4)") == ["%rax", "8(%rsp,%rcx,4)"]

        sib_asm = """.type g,@function
g:
    movq (%rsp,%rax,8), %rax
    movq %rax, 8(%rsp,%rax,8)
    addq $1, 8(%rsp,%rax,8)
    lock addq $1, 8(%rsp,%rax,8)
    leaq 16(%rsp,%rax,8), %rdi
    fstp %st(1)
    ret
.size g,.-g
"""
        sib = scorer.instruction_counts(scorer.assembly_functions(sib_asm)["g"])
        assert sib["stack_operands"] == 4, sib
        assert sib["loads"] == 3 and sib["stores"] == 3, sib

        # GCC's cached front end supports UBSan even when its optional
        # libubsan runtime is not shipped. Trap every enabled check instead of
        # borrowing an unrelated older runtime or silently skipping sanitizing.
        sanitizer_flags = ["-fsanitize=undefined,float-cast-overflow",
                           "-fsanitize-trap=undefined,float-cast-overflow",
                           "-fno-sanitize-recover=all"]
        for name, body in (
            ("signed_overflow", "volatile int x = 2147483647; return x + 1;"),
            ("float_cast_overflow", "volatile double x = 1e100; return (int)x;"),
        ):
            bad = root / f"intentional_{name}.c"
            bad.write_text(f"int main(void) {{ {body} }}\n")
            try:
                scorer.check_correctness("gcc", bad, "2", sanitizer_flags)
            except RuntimeError as error:
                assert "program failed" in str(error), str(error)
                assert f"exit={-signal.SIGILL}" in str(error), str(error)
            else:
                raise AssertionError(f"UBSan failed to trap intentional {name}")

        levels = ("0", "1", "2", "3") if args.full else ("0", "2")
        for src in files_a:
            reference = scorer.check_correctness("gcc", src, "0", [])
            for opt in levels:
                result = scorer.check_correctness("gcc", src, opt, [], reference)
                assert result == reference
            scorer.check_correctness("gcc", src, "2", sanitizer_flags, reference)
    print(f"PASS: deterministic 20-kernel corpus, assembly counters, GCC checksum matrix {levels}, UBSan trap O2 (two intentional-UB controls)")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
