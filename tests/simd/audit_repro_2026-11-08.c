/*
 * SIMD implementation-audit reproducers — §9c of
 * engineering/SIMD-IMPLEMENTATION-AUDIT-2026-11-08.md, 2026-11-08.
 *
 * This file is a *library of entry points*, not a passing test suite.  Each
 * entry point is selected by argv[1] and driven by
 * tests/simd/check_audit_2026-11-08.py, which knows which rows reproduce an
 * open finding (expected to fail) and which are controls (must pass).
 *
 * Entry points (see `list`):
 *   sa02        SA-02  full FMA-orientation matrix, exact powers of two
 *   sa02_ctl    SA-02  control orientations only (must always pass)
 *   sa05        SA-05  512-bit maddubs memory-fold operand roles
 *   sa05_ctl    SA-05  intrinsic-free scalar reference (must always pass)
 *   sa06        SA-06  ARX bypass-edge state materialization (differential)
 *   sa07        SA-07  ARX word-phi terminator use (differential, ICE class)
 *   sa01        SA-01  two-accumulator dot product, numeric self-check
 *   sa01_ctl    SA-01  single-accumulator dot product, numeric self-check
 *   all / list  run everything / enumerate entry points
 *
 * Exactness.  x = {1.5, 2.5, ...}, k = 4, z = {3, 5, ...} are powers of two,
 * so x*k - z is exact in binary32 and binary64, fused or unfused.  A mismatch
 * is therefore always a codegen defect, never a rounding artefact.  The
 * signed/unsigned roles in the maddubs kernel are checked against an
 * in-binary scalar reference with language-level saturating arithmetic.
 *
 * UB / portability.  C99, fixed-width integers, unsigned wraparound only,
 * float bit patterns move through memcpy (no strict-aliasing pun), every
 * array index is statically bounded, no allocation, no signed overflow, no
 * unaligned scalar accesses.  AVX-512 code is behind predefined macros and
 * has a scalar fallback with an identical digest on every other target
 * (x86-64 without AVX-512, i686, AArch64, RISC-V).
 *
 * The ISA-specific asm probes (SA-01/03/04/13/33) are generated by the
 * driver from small standalone translation units; `sa01` here pins the
 * numeric contract of the same two-accumulator kernel so the C kernel and
 * the asm oracle cannot drift apart unnoticed.
 */
