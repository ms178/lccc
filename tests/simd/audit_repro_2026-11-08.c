#define ENTRY_COUNT (sizeof(ENTRIES) / sizeof(ENTRIES[0]))

static const entry_t *find_entry(const char *name)
{
    size_t i;
    for (i = 0; i < ENTRY_COUNT; i++) {
        if (strcmp(ENTRIES[i].name, name) == 0) return &ENTRIES[i];
    }
    return NULL;
}

int main(int argc, char **argv)
{
    const char *mode = (argc > 1) ? argv[1] : "all";

    if (strcmp(mode, "list") == 0) {
        size_t i;
        for (i = 0; i < ENTRY_COUNT; i++)
            printf("%s\t%s\n", ENTRIES[i].name, ENTRIES[i].item);
        return 0;
    }
    if (strcmp(mode, "all") == 0) {
        size_t i;
        int bad = 0;
        for (i = 0; i < ENTRY_COUNT; i++) bad |= ENTRIES[i].fn();
        return bad;
    }
    {
        const entry_t *e = find_entry(mode);
        if (!e) {
            fprintf(stderr, "unknown entry point: %s\n", mode);
            return 2;
        }
        return e->fn();
    }
}
