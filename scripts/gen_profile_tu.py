#!/usr/bin/env python3
"""Generate a deterministic synthetic C translation unit for compiler profiling.

The output is a self-contained, warning-free C file whose shape exercises the
paths that dominate compile time on real code: integer/FP arithmetic chains,
loops with memory traffic over arrays and structs, switches, calls between the
generated functions, and comparisons that feed branches.  Determinism matters:
the same (seed, nfuncs) pair must produce byte-identical source on every host,
so profile baselines taken in different sessions stay comparable.

Usage: gen_profile_tu.py SEED NFUNCS > out.c
"""

import sys


class Rng:
    """xorshift64* — deterministic across Python versions, unlike random."""

    def __init__(self, seed: int) -> None:
        self.s = seed & 0xFFFFFFFFFFFFFFFF or 0x9E3779B97F4A7C15

    def next(self) -> int:
        s = self.s
        s ^= (s >> 12) & 0xFFFFFFFFFFFFFFFF
        s ^= (s << 25) & 0xFFFFFFFFFFFFFFFF
        s ^= (s >> 27) & 0xFFFFFFFFFFFFFFFF
        self.s = s
        return (s * 0x2545F4914F6CDD1D) & 0xFFFFFFFFFFFFFFFF

    def below(self, n: int) -> int:
        return self.next() % n

    def pick(self, seq):
        return seq[self.below(len(seq))]


INT_OPS = ["+", "-", "^", "|", "&"]
FP_OPS = ["+", "-", "*"]


def gen_func(r: Rng, idx: int, nfuncs: int) -> str:
    """One function: locals, a loop over a stack array, a switch, calls."""
    lines = []
    nlocals = 3 + r.below(5)
    lines.append(f"static long f{idx}(long a, long b) {{")
    lines.append(f"    long v0 = a {r.pick(INT_OPS)} {1 + r.below(97)};")
    for i in range(1, nlocals):
        src = r.below(i)
        lines.append(
            f"    long v{i} = v{src} {r.pick(INT_OPS)} "
            f"(b {r.pick(INT_OPS)} {1 + r.below(63)});"
        )
    # Loop with array traffic (sized so -O2 can still unroll/vectorize some).
    asz = 8 + r.below(24)
    lines.append(f"    long arr[{asz}];")
    lines.append(f"    for (int i = 0; i < {asz}; i++)")
    lines.append(
        f"        arr[i] = v{r.below(nlocals)} {r.pick(INT_OPS)} (long)i * "
        f"{1 + r.below(7)};"
    )
    lines.append(f"    for (int i = 1; i < {asz}; i++)")
    lines.append(
        f"        arr[i] {r.pick(INT_OPS)}= arr[i - 1] >> {r.below(3) + 1};"
    )
    # FP block: double chain folded back into the integer result.
    lines.append(f"    double d = (double)v{r.below(nlocals)} * 0.5;")
    for _ in range(2 + r.below(3)):
        lines.append(f"    d = d {r.pick(FP_OPS)} {1 + r.below(9)}.{r.below(10)};")
    # Switch over a derived scrutinee.
    ncases = 3 + r.below(4)
    lines.append(f"    switch ((v{r.below(nlocals)} ^ a) & {ncases - 1}) {{")
    for c in range(ncases - 1):
        lines.append(
            f"    case {c}: v0 {r.pick(INT_OPS)}= v{r.below(nlocals)} + {c}; break;"
        )
    lines.append(f"    default: v0 = v0 {r.pick(INT_OPS)} b; break;")
    lines.append("    }")
    # Call a previously defined function (forms a DAG, no recursion).
    if idx > 0:
        callee = r.below(idx)
        lines.append(f"    v0 ^= f{callee}(v{r.below(nlocals)}, arr[{r.below(asz)}]);")
    lines.append(f"    return v0 + arr[{r.below(asz)}] + (long)d;")
    lines.append("}")
    return "\n".join(lines)


def main() -> int:
    seed, nfuncs = int(sys.argv[1]), int(sys.argv[2])
    r = Rng(seed)
    out = [
        "/* Auto-generated by scripts/gen_profile_tu.py "
        f"(seed={seed}, nfuncs={nfuncs}). Deterministic. */"
    ]
    for i in range(nfuncs):
        out.append(gen_func(r, i, nfuncs))
    # Keep EVERY generated function alive through codegen: a direct call to
    # each from main defeats static-function DCE, so -O1/-O2 compile, optimize
    # and emit all of them (the point of a compiler-profiling workload).
    out.append("int main(void) {")
    out.append("    long acc = 0;")
    for i in range(nfuncs):
        out.append(f"    acc ^= f{i}(acc + {i}, {i * 3 + 1});")
    out.append("    return (int)(acc & 0x7f);")
    out.append("}")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
