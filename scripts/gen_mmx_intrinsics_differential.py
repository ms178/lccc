#!/usr/bin/env python3
"""Generate tests/regression/mmx_intrinsics_differential.c.

The test drives every __m64 API lccc provides against GCC 16.2 (the corpus
runner compares the outputs). Run without arguments to regenerate it, or
with --check to reject drift.
"""
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / 'tests/regression/mmx_intrinsics_differential.c'
BIN64 = ['and_si64','andnot_si64','or_si64','xor_si64','add_pi8','add_pi16','add_pi32','sub_pi8',
 'sub_pi16','sub_pi32','adds_pi8','adds_pi16','adds_pu8','adds_pu16','subs_pi8','subs_pi16','subs_pu8',
 'subs_pu16','mullo_pi16','mulhi_pi16','madd_pi16','packs_pi32','packs_pi16','packs_pu16','cmpeq_pi8',
 'cmpeq_pi16','cmpeq_pi32','cmpgt_pi8','cmpgt_pi16','cmpgt_pi32','unpacklo_pi8','unpackhi_pi8',
 'unpacklo_pi16','unpackhi_pi16','unpacklo_pi32','unpackhi_pi32','max_pi16','max_pu8','min_pi16',
 'min_pu8','mulhi_pu16','avg_pu8','avg_pu16','sad_pu8']
SHIFT = ['slli_pi16','slli_pi32','slli_si64','srli_pi16','srli_pi32','srli_si64','srai_pi16','srai_pi32']
M64_TO_PS = ['cvtpi16_ps','cvtpu16_ps','cvtpi8_ps','cvtpu8_ps']
PS_TO_M64 = ['cvtps_pi32','cvttps_pi32','cvtps_pi16','cvtps_pi8']
out = []
w = out.append
w('''/* Differential test of every __m64 intrinsic lccc provides (mmintrin.h and
 * xmmintrin.h, 90 entry points) against GCC 16.2's real-MMX implementation.
 * __m64 is only built and read through memcpy, so the test is independent
 * of the type's representation. Inputs are lane-boundary patterns followed
 * by xorshift values; float inputs cover the rounding ties, the saturation
 * and integer-indefinite edges, NaN and the infinities. Each function prints
 * its own hash, so a mismatch names the intrinsic. _mm_empty() after each
 * call keeps GCC's MMX code x87-safe on i686. Generated by
 * scripts/gen_mmx_intrinsics_differential.py (--check rejects drift); the
 * -m32 sibling is mmx_intrinsics_differential_m32.c. */
#include <xmmintrin.h>
#include <stdio.h>
#include <string.h>

#define ITER 96
static unsigned long long seed = 0x9e3779b97f4a7c15ull;
static unsigned long long rnd(void)
{
	seed ^= seed << 13;
	seed ^= seed >> 7;
	seed ^= seed << 17;
	return seed;
}
static const unsigned long long spec[] = {
	0, ~0ull, 0x8000800080008000ull, 0x7fff7fff7fff7fffull, 0x8080808080808080ull,
	0x7f7f7f7f7f7f7f7full, 0x0001000100010001ull, 0xffff0000ffff0000ull, 0x0000000080000000ull,
	0x7fffffff80000000ull, 0x00ff00ff00ff00ffull, 0xff00ff00ff00ff00ull, 0x0102030405060708ull,
	0xfffefdfcfbfaf9f8ull, 0x8001800180018001ull, 0x00007fff00008000ull,
};
#define NSPEC (int)(sizeof spec / sizeof spec[0])
static unsigned long long val(int i, int j)
{
	if (i < NSPEC * NSPEC / 4)
		return spec[(i * 5 + j * 3 + (j ? i / NSPEC : 0)) % NSPEC];
	return rnd();
}
static const float fspec[] = {
	0.0f, -0.0f, 1.5f, -1.5f, 2.5f, -2.5f, 0.5f, -0.5f, 32767.5f, 32768.0f, -32768.5f, -32769.0f,
	127.5f, 128.0f, -128.5f, -129.0f, 255.5f, 2147483520.0f, 2147483648.0f, -2147483648.0f,
	-2147483904.0f, 1e10f, -1e10f, 1e-40f, __builtin_nanf(""), -__builtin_inff(), __builtin_inff(),
	65535.5f, 3.4e38f, -7.5f,
};
#define NFSPEC (int)(sizeof fspec / sizeof fspec[0])
static float fval(int i)
{
	if (i < NFSPEC * 2)
		return fspec[(i * 7) % NFSPEC];
	return (float)((long long)(rnd() % 160001) - 80000) * 0.75f;
}
static __m64 M(unsigned long long v)
{
	__m64 m;
	memcpy(&m, &v, sizeof m);
	return m;
}
static __m128 PS(int i)
{
	float f[4];
	for (int k = 0; k < 4; k++) /* sequenced: initializer order is unspecified */
		f[k] = fval(4 * i + k);
	__m128 r;
	memcpy(&r, f, sizeof r);
	return r;
}
static unsigned long long h;
static void mix(const void *p, unsigned n)
{
	const unsigned char *b = p;
	for (unsigned k = 0; k < n; k++)
		h = (h ^ b[k]) * 1099511628211ull;
}
#define BEGIN() (h = 1469598103934665603ull, seed = 0x9e3779b97f4a7c15ull)
#define END(name) printf("%-20s %016llx\\n", name, h)
#define MIX(x)                          \\
	do {                            \\
		__typeof__(x) t_ = (x); \\
		_mm_empty();            \\
		mix(&t_, sizeof t_);    \\
	} while (0)
/* Float results: NaN payloads are canonicalised (the oracle is bitwise). */
static void mixps(__m128 v)
{
	float f[4];
	memcpy(f, &v, sizeof f);
	for (int k = 0; k < 4; k++)
		if (f[k] != f[k])
			f[k] = __builtin_nanf("");
	mix(f, sizeof f);
}
''')
for n in BIN64:
    w(f'__attribute__((noinline)) static void t_{n}(void)\n{{\n\tBEGIN();\n\tfor (int i = 0; i < ITER; i++)\n\t{{\n\t\tunsigned long long a = val(i, 0), b = val(i, 1);\n\t\tMIX(_mm_{n}(M(a), M(b)));\n\t}}\n\tEND("{n}");\n}}')
for n in SHIFT:
    w(f'__attribute__((noinline)) static void t_{n}(void)\n{{\n\tstatic const int c[] = {{ 0, 1, 3, 7, 8, 15, 16, 17, 31, 32, 33, 63, 64, 65, 200, 255 }};\n\tBEGIN();\n\tfor (int i = 0; i < ITER; i++)\n\t\tMIX(_mm_{n}(M(val(i, 0)), c[i % 16]));\n\tEND("{n}");\n}}')
    w(f'__attribute__((noinline)) static void t_{n}_k(void)\n{{\n\tBEGIN();\n\tfor (int i = 0; i < ITER; i++) {{\n\t\tMIX(_mm_{n}(M(val(i, 0)), 0));\n\t\tMIX(_mm_{n}(M(val(i, 0)), 5));\n\t\tMIX(_mm_{n}(M(val(i, 0)), 16));\n\t\tMIX(_mm_{n}(M(val(i, 0)), 40));\n\t}}\n\tEND("{n}_k");\n}}')
for n in M64_TO_PS:
    w(f'__attribute__((noinline)) static void t_{n}(void)\n{{\n\tBEGIN();\n\tfor (int i = 0; i < ITER; i++) {{\n\t\t__m128 r = _mm_{n}(M(val(i, 0)));\n\t\t_mm_empty();\n\t\tmixps(r);\n\t}}\n\tEND("{n}");\n}}')
for n in PS_TO_M64:
    w(f'__attribute__((noinline)) static void t_{n}(void)\n{{\n\tBEGIN();\n\tfor (int i = 0; i < ITER; i++)\n\t\tMIX(_mm_{n}(PS(i)));\n\tEND("{n}");\n}}')
w('''__attribute__((noinline)) static void t_misc(void)
{
	BEGIN();
	for (int i = 0; i < ITER; i++) {
		unsigned long long a = val(i, 0), b = val(i, 1);
		int x = (int)a, y = (int)(a >> 32);
		MIX(_mm_setzero_si64());
		MIX(_mm_cvtsi32_si64(x));
		MIX(_mm_cvtsi64_si32(M(b)));
		MIX(_mm_set_pi32(x, y));
		MIX(_mm_setr_pi32(x, y));
		MIX(_mm_set_pi16((short)a, (short)(a >> 16), (short)(a >> 32), (short)(a >> 48)));
		MIX(_mm_setr_pi16((short)a, (short)(a >> 16), (short)(a >> 32), (short)(a >> 48)));
		MIX(_mm_set_pi8((char)a, (char)(a >> 8), (char)(a >> 16), (char)(a >> 24), (char)(a >> 32),
				(char)(a >> 40), (char)(a >> 48), (char)(a >> 56)));
		MIX(_mm_set1_pi32(y));
		MIX(_mm_set1_pi16((short)b));
		MIX(_mm_set1_pi8((char)b));
		MIX(_mm_movemask_pi8(M(a)));
#ifdef __x86_64__
		MIX(_mm_cvtsi64_m64((long long)a));
		MIX(_mm_cvtm64_si64(M(b)));
#endif
	}
	END("misc");
}
__attribute__((noinline)) static void t_lanes(void)
{
	BEGIN();
	for (int i = 0; i < ITER; i++) {
		__m64 a = M(val(i, 0));
		int d = (int)val(i, 1);
		MIX(_mm_extract_pi16(a, 0));
		MIX(_mm_extract_pi16(a, 1));
		MIX(_mm_extract_pi16(a, 2));
		MIX(_mm_extract_pi16(a, 3));
		/* rvalue operands */
		MIX(_mm_extract_pi16(_mm_add_pi16(a, M((unsigned long long)d)), 1));
		MIX(_mm_insert_pi16(_mm_xor_si64(a, a), d, 2));
		MIX(_mm_shuffle_pi16(_mm_sub_pi16(a, M((unsigned long long)d)), 0x6c));
		MIX(_mm_insert_pi16(a, d, 0));
		MIX(_mm_insert_pi16(a, d, 1));
		MIX(_mm_insert_pi16(a, d, 2));
		MIX(_mm_insert_pi16(a, d, 3));
		MIX(_mm_shuffle_pi16(a, 0x00));
		MIX(_mm_shuffle_pi16(a, 0x1b));
		MIX(_mm_shuffle_pi16(a, 0xe4));
		MIX(_mm_shuffle_pi16(a, 0x4e));
		MIX(_mm_shuffle_pi16(a, 0xb1));
		MIX(_mm_shuffle_pi16(a, 0xff));
		MIX(_mm_shuffle_pi16(a, 0x93));
		MIX(_mm_shuffle_pi16(a, 0x39));
	}
	END("lanes");
}
__attribute__((noinline)) static void t_cvtpi32_ps(void)
{
	BEGIN();
	for (int i = 0; i < ITER; i++) {
		__m128 base = PS(i);
		unsigned long long a = val(i, 0);
		__m128 r = _mm_cvtpi32_ps(base, M(a));
		_mm_empty();
		mixps(r);
		a = val(i, 0);
		unsigned long long b = val(i, 1);
		r = _mm_cvtpi32x2_ps(M(a), M(b));
		_mm_empty();
		mixps(r);
	}
	END("cvtpi32_ps");
}
__attribute__((noinline)) static void t_memory(void)
{
	BEGIN();
	for (int i = 0; i < ITER; i++) {
		__m64 buf[4];
		char bytes[24];
		unsigned long long a = val(i, 0), n = val(i, 1);
		memset(buf, 0x3c, sizeof buf);
		memset(bytes, 0x5a, sizeof bytes);
		__m128 v = PS(i);
		_mm_storel_pi(&buf[1], v);
		_mm_storeh_pi(&buf[2], v);
		__m128 b1 = PS(i + 1), b2 = PS(i + 2);
		__m128 l = _mm_loadl_pi(b1, &buf[2]);
		__m128 hi = _mm_loadh_pi(b2, &buf[1]);
		_mm_maskmove_si64(M(a), M(n), bytes + 8);
		_mm_stream_pi(&buf[3], M(a ^ n));
		_mm_empty();
		mix(buf, sizeof buf);
		mix(bytes, sizeof bytes);
		mixps(l);
		mixps(hi);
	}
	END("memory");
}''')
fns = [f't_{n}' for n in BIN64] + [x for n in SHIFT for x in (f't_{n}', f't_{n}_k')] + \
      [f't_{n}' for n in M64_TO_PS + PS_TO_M64] + ['t_misc', 't_lanes', 't_cvtpi32_ps', 't_memory']
w('int main(void)\n{\n' + ''.join(f'\t{f}();\n' for f in fns) + '\treturn 0;\n}')
text = '\n'.join(out) + '\n'
if sys.argv[1:] == ['--check']:
    if OUTPUT.read_text() != text:
        sys.exit(f'{OUTPUT} is stale: run {Path(__file__).name}')
elif sys.argv[1:]:
    sys.exit('usage: gen_mmx_intrinsics_differential.py [--check]')
else:
    OUTPUT.write_text(text)
