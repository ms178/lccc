#!/usr/bin/env python3
"""Generate `tests/regression/f128_classify_truth_table.c`.

The fixture checks the seven binary128 classifiers (`__builtin_isnan`,
`__builtin_isinf`, `__builtin_isfinite`, `__builtin_isnormal`,
`__builtin_signbit`, `__builtin_isinf_sign`, `__builtin_fpclassify`) on 19
boundary bit patterns, including the subnormal, infinity, quiet-NaN and
signaling-NaN cases that floating-point arithmetic cannot reliably produce.

WHY A GENERATOR: the expected value of every cell is derived *here*, from the
bit pattern, with integer arithmetic on the sign/exponent/mantissa fields of
IEEE 754-2019 clause 3 -- no compiler is consulted, so the fixture is an
independent oracle rather than a snapshot of what some implementation happened
to print (which is how a wrong `fpclassify` survives a self-consistent test
suite). Building the pattern through a `union { _Float128 f; unsigned __int128
u; }` is what makes every pattern reachable.

The defect this pins: `_Float128` reached the classifier lowering in a `U128`
carrier while `long double` is x87 extended in memory, so the builtins either
called the libc `__*l` entry points or fell into the `f64` mask path.
`__builtin_isnan(nan)` returned 0, `__builtin_isinf(inf)` returned 0 and
`__builtin_isfinite(inf)` returned 1 for binary128.

`__builtin_signbit` only has to be non-zero for a negative value (GCC 16.2
returns 0x08, Clang 23.1.4 0x80, lccc 0x01), so the table stores `signbit != 0`.

Usage::

    scripts/gen_f128_classify_truth_table.py           # write the fixture
    scripts/gen_f128_classify_truth_table.py --check    # verify it is current

Clang 23.1.4 does not implement the C23 spelling `_Float128` at all; it can run
this fixture through `__float128` (`sed 's/_Float128/__float128/g'`), which is
how the three-way check in the campaign report was done.
"""

from __future__ import annotations

import argparse
import sys

OUT = "tests/regression/f128_classify_truth_table.c"

PATTERNS = [
    ("zero", 0x00000000000000000000000000000000),
    ("neg_zero", 0x80000000000000000000000000000000),
    ("min_subnormal", 0x00000000000000000000000000000001),
    ("max_subnormal", 0x0000FFFFFFFFFFFFFFFFFFFFFFFFFFFF),
    ("min_normal", 0x00010000000000000000000000000000),
    ("one", 0x3FFF0000000000000000000000000000),
    ("neg_one", 0xBFFF0000000000000000000000000000),
    ("max_finite", 0x7FFEFFFFFFFFFFFFFFFFFFFFFFFFFFFF),
    ("neg_max_finite", 0xFFFEFFFFFFFFFFFFFFFFFFFFFFFFFFFF),
    ("pos_inf", 0x7FFF0000000000000000000000000000),
    ("neg_inf", 0xFFFF0000000000000000000000000000),
    ("qnan", 0x7FFF8000000000000000000000000000),
    ("neg_qnan", 0xFFFF8000000000000000000000000000),
    ("snan", 0x7FFF0000000000000000000000000001),
    ("qnan_allbits", 0x7FFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF),
    ("two", 0x40000000000000000000000000000000),
    ("below_one", 0x3FFEFFFFFFFFFFFFFFFFFFFFFFFFFFFF),
    ("mantissa_hi_set", 0x3FFF00000000FFFFFFFFFFFFFFFFFFFF),
    ("mantissa_lo_set", 0x3FFF0000000000000000000000000001),
]

FP_NAN, FP_INF, FP_NORMAL, FP_SUBNORMAL, FP_ZERO = 0, 1, 2, 3, 4


def classify(bits: int) -> int:
    """`fpclassify` per IEEE 754-2019 clause 3, from the raw fields."""
    exponent = (bits >> 112) & 0x7FFF
    mantissa = bits & ((1 << 112) - 1)
    if exponent == 0x7FFF:
        return FP_NAN if mantissa else FP_INF
    if exponent == 0:
        return FP_ZERO if mantissa == 0 else FP_SUBNORMAL
    return FP_NORMAL


def rows() -> list[tuple]:
    table = []
    for name, bits in PATTERNS:
        classification = classify(bits)
        sign = (bits >> 127) & 1
        table.append(
            (
                name,
                bits,
                1 if classification == FP_NAN else 0,
                1 if classification == FP_INF else 0,
                1 if classification in (FP_NORMAL, FP_SUBNORMAL, FP_ZERO) else 0,
                1 if classification == FP_NORMAL else 0,
                sign,
                0 if classification != FP_INF else (-1 if sign else 1),
                classification,
            )
        )
    return table


def render() -> str:
    table = rows()
    entries = "\n".join(
        '    { "%s", U128(0x%016XULL, 0x%016XULL), %d, %d, %d, %d, %d, %d, %d },'
        % (name, bits >> 64, bits & ((1 << 64) - 1), isnan, isinf, isfinite, isnormal, sign, inf_sign, cls)
        for name, bits, isnan, isinf, isfinite, isnormal, sign, inf_sign, cls in table
    )
    return f'''/* IEEE 754 binary128 classification, checked against an independent oracle.
 *
 * GENERATED by `scripts/gen_f128_classify_truth_table.py` -- do not edit by
 * hand; run the script instead, and run it with `--check` to verify the file is
 * current.
 *
 * Every expected value below was computed from the bit pattern with integer
 * arithmetic on the sign/exponent/mantissa fields (IEEE 754-2019 clause 3), not
 * taken from any compiler's output. The fixture builds each `_Float128` from its
 * raw 128-bit pattern through a union, so it exercises the subnormal, infinity,
 * quiet-NaN and signaling-NaN cases that arithmetic cannot reliably produce.
 *
 * The defect this pins: lccc classified `_Float128` either through the libc x87
 * `__*l` long-double entry points or through its f64 mask path, because
 * `_Float128` and `long double` are both 16 bytes but are different formats.
 * `__builtin_isnan(nan)` returned 0, `__builtin_isinf(inf)` returned 0 and
 * `__builtin_isfinite(inf)` returned 1.
 *
 * `__builtin_signbit` only has to be non-zero for a negative value (gcc returns
 * 0x08, clang 0x80, lccc 0x01), so the table stores `signbit != 0`.
 */
#include <stdio.h>
#include <string.h>

typedef unsigned __int128 u128;

union Bits {{
    _Float128 f;
    u128 u;
}};

struct Expect {{
    const char *name;
    u128 bits;
    int isnan;
    int isinf;
    int isfinite;
    int isnormal;
    int signbit;
    int isinf_sign;
    int fpclassify;
}};

#define U128(hi, lo) (((u128)(hi) << 64) | (u128)(lo))

static const struct Expect TABLE[] = {{
{entries}
}};

static int failures;

static void row(const struct Expect *e) {{
    union Bits b;
    memset(&b, 0, sizeof b);
    b.u = e->bits;
    _Float128 f = b.f;
    int isnan = __builtin_isnan(f) != 0;
    int isinf = __builtin_isinf(f) != 0;
    int isfinite = __builtin_isfinite(f) != 0;
    int isnormal = __builtin_isnormal(f) != 0;
    int signbit = __builtin_signbit(f) != 0;
    int isinf_sign = (int)__builtin_isinf_sign(f);
    int fpclassify = __builtin_fpclassify(0, 1, 2, 3, 4, f);
    if (isnan == e->isnan && isinf == e->isinf && isfinite == e->isfinite &&
        isnormal == e->isnormal && signbit == e->signbit &&
        isinf_sign == e->isinf_sign && fpclassify == e->fpclassify) {{
        return;
    }}
    ++failures;
    printf("FAIL %s: got isnan=%d isinf=%d isfinite=%d isnormal=%d signbit=%d "
           "isinf_sign=%d fpclassify=%d\\n",
           e->name, isnan, isinf, isfinite, isnormal, signbit, isinf_sign, fpclassify);
    printf("     want isnan=%d isinf=%d isfinite=%d isnormal=%d signbit=%d "
           "isinf_sign=%d fpclassify=%d\\n",
           e->isnan, e->isinf, e->isfinite, e->isnormal, e->signbit, e->isinf_sign,
           e->fpclassify);
}}

int main(void) {{
    for (size_t i = 0; i < sizeof TABLE / sizeof TABLE[0]; ++i) {{
        row(&TABLE[i]);
    }}
    printf("%s f128_classify_truth_table (%zu patterns)\\n", failures ? "FAIL" : "PASS",
           sizeof TABLE / sizeof TABLE[0]);
    return failures != 0;
}}
'''


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = render()
    if args.check:
        try:
            current = open(OUT, "r", encoding="utf-8").read()
        except OSError:
            current = None
        if current != source:
            print(f"gen_f128_classify_truth_table: {OUT} is out of date", file=sys.stderr)
            return 1
        print(f"gen_f128_classify_truth_table: {OUT} is current")
        return 0
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(source)
    print(f"gen_f128_classify_truth_table: wrote {OUT} ({len(source)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
