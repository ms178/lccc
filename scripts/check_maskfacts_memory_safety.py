#!/usr/bin/env python3
"""Adversarial EXECUTED differential for the masked-compare load forwarding.

WHY THIS EXISTS
---------------
Round 11 removed the write-through vector HOME by letting
`vector_temp_promotion::fuse_vector_loads` forward the ORIGINAL load address
into the `vpcmp*` operand, and by letting the x86 emitter read that address
as an EVEX memory src2.  That transformation is only correct if the object's
bytes cannot change between the original load and the compare.  A unit test
of the pass's internal guards is not enough: the proof must be exercised by
programs that TRY to invalidate it, and the result compared byte-for-byte
against GCC 16.2 and Clang 23.1.5.

The generated fixture deliberately includes:
  * writes to the loaded object BETWEEN the load and the compare (128/256/512);
  * an opaque `noinline` call that writes the object in between;
  * volatile objects and TLS objects (which the emitter must refuse);
  * heap pointers with provable aliasing, computed offsets and negative strides;
  * overlapping regions of one object, partial stores, `x op x` and the
    operand-independent predicates 3/7 combined with an intervening write;
  * an `extern` data symbol supplied by a SECOND translation unit (tests the
    RIP-relative relocation of the folded memory operand);
  * three clean positive controls, asserted at the ASSEMBLY level to prove
    the optimization actually FIRED (no stack frame, `B(%rip)` as src2).

Seven binaries (LCCC ON/OFF, GCC 16.2, Clang 23.1.5, and PIE variants of
LCCC/GCC/Clang) must produce byte-identical stdout.  `--self-test` corrupts one
oracle line and requires the evaluator to REJECT it, so a vacuous comparison
cannot pass.

Usage:
    scripts/check_maskfacts_memory_safety.py [--json PATH] [--write-fixture]
    scripts/check_maskfacts_memory_safety.py --self-test
"""
