def generate_source() -> tuple[str, list[str]]:
    out = [HEADER]
    names = []
    for name, body in CASES:
        names.append(name)
        out.append(f"__attribute__((noinline)) static unsigned long long {name}(int seed) {{")
        out.append("    unsigned long long out = 0;")
        out.append("    (void)seed;")
        out.append(body.rstrip())
        out.append("    return out;")
        out.append("}")
        out.append("")
    out.append("#define CASE(name) do { \\")
    out.append('    printf("%s %016llx\\n", #name, (unsigned long long)name(argc)); \\')
    out.append("} while (0)")
    out.append("")
    out.append("int main(int argc, char **argv) {")
    out.append("    (void)argv;")
    out.append("    A[0] = (unsigned char)argc; B[0] = (unsigned char)(argc + 1);")
    out.append("    B[3] = (unsigned char)(argc ^ 0x2a); A[5] = (unsigned char)(argc ^ 0x19);")
    out.append("    V[0] = (unsigned char)(argc + 2); T[0] = (unsigned char)(argc + 3);")
    for name, _ in CASES:
        out.append(f"    CASE({name});")
    out.append("    return 0;")
    out.append("}")
    return "\n".join(out) + "\n", names


def run(cmd: list[str], env: dict | None = None, timeout: int = 300):
    return subprocess.run(cmd, capture_output=True, text=True, env=env, timeout=timeout)


def tool(name: str) -> str:
    p = CACHE_BIN / name
    return str(p) if p.exists() else shutil.which(name) or name


def compile_and_run(tmp: Path, label: str, cmd: list[str], env: dict, src: Path, ext: Path, link: list[str] | None = None) -> str:
    obj = tmp / f"{label}_main.o"
    eobj = tmp / f"{label}_extern.o"
    exe = tmp / label
    for c, o in ((src, obj), (ext, eobj)):
        cp = run(cmd + ["-Wall", "-Wextra", "-Werror", "-c", str(c), "-o", str(o)], env=env)
        if cp.returncode != 0:
            raise RuntimeError(f"{label} compile {c.name} rc={cp.returncode}\n{cp.stderr[-1500:]}")
        if cp.stderr.strip():
            raise RuntimeError(f"{label} emitted diagnostics for {c.name}: {cp.stderr[-800:]}")
    cp = run(cmd + (link or []) + [str(obj), str(eobj), "-o", str(exe)], env=env)
    if cp.returncode != 0:
        raise RuntimeError(f"{label} link rc={cp.returncode}\n{cp.stderr[-1500:]}")
    rp = run([str(exe), "7"], env=env, timeout=120)
    if rp.returncode != 0:
        raise RuntimeError(f"{label} run rc={rp.returncode}\n{rp.stderr[-1000:]}")
    return rp.stdout


def positive_control_asm(tmp: Path, lccc: str, env: dict, src: Path) -> tuple[list[str], list[str]]:
    """The three CLEAN cases must actually use the folded form.  Without this
    assertion a compiler that simply never forwards would also pass the
    executed oracle."""
    failures: list[str] = []
    notes: list[str] = []
    asm = tmp / "lccc_control.s"
    cp = run([lccc] + FLAGS + ["-I", "include", "-S", str(src), "-o", str(asm)], env=env)
    if cp.returncode != 0:
        return [f"control -S rc={cp.returncode}"], []
    text = asm.read_text()
    import re
    for name in ("clean_eq_128", "clean_eq_256", "clean_eq_512"):
        m = re.search(rf"^{name}:.*?^\.size {name}", text, re.M | re.S)
        if not m:
            failures.append(f"{name}: function body missing from LCCC asm")
            continue
        body = m.group(0)
        if not any(line.strip().startswith("vpcmp") and "B(%rip)" in line
                   for line in body.splitlines()):
            failures.append(f"{name}: EVEX memory src2 fold did NOT fire: {body}")
        if "(%rsp)" in body or "subq" in body:
            failures.append(f"{name}: unexpected stack frame (HOME roundtrip): {body}")
        else:
            notes.append(f"{name}: register-only, B(%rip) folded, no frame")
    # NEGATIVE structural control: a write between the load and the compare
    # must NOT be forwarded as `vpcmp ... A(%rip)` (that would re-read A).
    for name in ("write_A_after_load_128", "write_A_after_load_512"):
        m = re.search(rf"^{name}:.*?^\.size {name}", text, re.M | re.S)
        if not m:
            failures.append(f"{name}: function body missing")
            continue
        body = m.group(0)
        bad = [l for l in body.splitlines()
               if l.strip().startswith("vpcmp") and "A(%rip)" in l]
        if bad:
            failures.append(f"{name}: forwarded a CHANGING source as src2: {bad}")
        else:
            notes.append(f"{name}: forwarding correctly refused")
    return failures, notes


def evaluate(outputs: dict[str, str], mutate: bool = False) -> tuple[list[str], list[str]]:
    oracle = outputs["gcc16"]
    if mutate:
        lines = oracle.splitlines()
        if lines:
            lines[0] = lines[0].replace(" ", " MUTATED ")
        oracle = "\n".join(lines) + "\n"
    failures: list[str] = []
    notes: list[str] = []
    for label, out in outputs.items():
        if out == oracle:
            notes.append(f"{label}: {len(out.splitlines())} case lines byte-identical to GCC 16.2")
        else:
            a, b = oracle.splitlines(), out.splitlines()
            diff = next(
                (f"line {i+1}: gcc={x!r} {label}={y!r}"
                 for i, (x, y) in enumerate(zip(a, b)) if x != y),
                f"length gcc={len(a)} {label}={len(b)}",
            )
            failures.append(f"{label} stdout differs from GCC 16.2 ({diff})")
    return failures, notes


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", type=Path)
    ap.add_argument("--write-fixture", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()

    src_text, names = generate_source()
    if args.write_fixture:
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(src_text)
        EXTERN_FIXTURE.write_text(EXTERN_DEF)
        print(f"wrote {FIXTURE} ({len(src_text.splitlines())} lines, {len(names)} cases)")
        print(f"wrote {EXTERN_FIXTURE}")

    if args.self_test:
        fake = {"gcc16": "clean_eq_128 0000000000000000\n",
                "lccc_on": "clean_eq_128 0000000000000000\n",
                "lccc_off": "clean_eq_128 0000000000000000\n",
                "clang23": "clean_eq_128 0000000000000000\n"}
        ok, _ = evaluate(fake)
        if ok:
            print("self-test FAIL: identical outputs were rejected", file=sys.stderr)
            return 1
        bad, _ = evaluate(fake, mutate=True)
        if not bad:
            print("self-test FAIL: corrupted oracle was ACCEPTED", file=sys.stderr)
            return 1
        print(f"self-test PASS: corruption detected ({bad[0][:70]})")
        return 0

    lccc = str(ROOT / "target" / "fastbuild" / "lccc")
    for binary in (lccc, tool("gcc-16"), tool("clang-23")):
        if not Path(binary).exists() and not shutil.which(binary):
            raise RuntimeError(f"missing compiler: {binary}")
    base = os.environ.copy()
    on = base.copy()
    on.pop("CCC_DISABLE_PASSES", None)
    off = base.copy()
    off["CCC_DISABLE_PASSES"] = "maskfacts"
    with tempfile.TemporaryDirectory(prefix="maskfacts_safety_") as td:
        tmp = Path(td)
        src, ext = tmp / "safety.c", tmp / "extern.c"
        src.write_text(src_text)
        ext.write_text(EXTERN_DEF)
        specs = [
            ("lccc_on", [lccc] + FLAGS + ["-I", "include"], on),
            ("lccc_off", [lccc] + FLAGS + ["-I", "include"], off),
            ("gcc16", [tool("gcc-16")] + FLAGS, base),
            ("clang23", [tool("clang-23")] + FLAGS, base),
        ]
        specs += [
            ("gcc16_pie", [tool("gcc-16")] + FLAGS + ["-fPIC"], base),
            ("clang23_pie", [tool("clang-23")] + FLAGS + ["-fPIC"], base),
            ("lccc_on_pie", [lccc] + FLAGS + ["-I", "include", "-fPIC"], on),
        ]
        outputs = {
            label: compile_and_run(
                tmp, label, cmd, env, src, ext,
                ["-pie"] if label.endswith("_pie") else None,
            )
            for label, cmd, env in specs
        }
        failures, notes = evaluate(outputs)
        asm_failures, asm_notes = positive_control_asm(tmp, lccc, on, src)
        failures += asm_failures
        notes += asm_notes
        receipt = {
            "cases": len(names),
            "source_sha256": hashlib.sha256(src_text.encode()).hexdigest(),
            "stdout_sha256": {k: hashlib.sha256(v.encode()).hexdigest()
                              for k, v in outputs.items()},
            "failures": failures,
            "notes": notes,
        }
        if args.json:
            args.json.write_text(json.dumps(receipt, indent=2) + "\n")
    for n in notes:
        print("  " + n)
    if failures:
        for f in failures:
            print("FAIL: " + f, file=sys.stderr)
        return 1
    print(
        f"PASS: {len(names)} adversarial cases, {len(outputs)} binaries, "
        "three-way stdout identical"
    )
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (RuntimeError, subprocess.TimeoutExpired) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(2)
