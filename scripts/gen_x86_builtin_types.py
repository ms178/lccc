#!/usr/bin/env python3
"""Generate native C result contracts from checked-in GCC type facts."""
import argparse
from collections import defaultdict
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
FACTS = ROOT / 'engineering/isa/gnu-x86-builtin-types.tsv'
OUTPUT = ROOT / 'src/common/x86_builtin_types.rs'
CONTRACT = ROOT / 'tests/regression/gnu_native_builtin_types.c'
SCALARS = {'VOID': 'Void', 'INT': 'Int', 'UINT': 'UInt',
           'INT64': 'LongLong', 'UINT64': 'ULongLong'}
ELEMENTS = {'QI': ('Char', 1), 'HI': ('Short', 2), 'SI': ('Int', 4),
            'DI': ('LongLong', 8), 'SF': ('Float', 4), 'DF': ('Double', 8)}


# Builtin families whose type contracts are checked but never executed.
RUNTIME_EXEMPT_PREFIXES = ('__builtin_ia32_vpdp', '__builtin_ia32_vsha512')

def result_expression(token):
    if token in SCALARS:
        return f'CType::{SCALARS[token]}'
    match = re.fullmatch(r'V(\d+)(QI|HI|SI|DI|SF|DF)', token)
    if not match:
        raise ValueError(f'unmapped GNU builtin result descriptor: {token}')
    element, size = ELEMENTS[match[2]]
    return f'CType::Vector(Box::new(CType::{element}), {int(match[1]) * size})'


def argument_vector_widths(descriptor):
    """Zero denotes a scalar/address parameter, never a vector IR carrier."""
    arguments = descriptor.split('_FTYPE_', 1)[1].split('_')
    widths = []
    for token in arguments:
        if token in ('VOID', 'COUNT', 'CONVERT', 'PTEST'):
            continue
        c_type(token)  # Refuse unrecognized tokens instead of guessing an ABI.
        vector = re.fullmatch(r'V(\d+)(QI|HI|SI|DI|SF|DF)', token)
        widths.append(int(vector[1]) * ELEMENTS[vector[2]][1] if vector else 0)
    return tuple(widths)


def argument_scalar_types(descriptor):
    scalar = {'INT': 'I32', 'SI': 'I32', 'UINT': 'U32', 'INT64': 'I64',
              'UINT64': 'U64', 'LONGLONG': 'I64', 'ULONGLONG': 'U64',
              'USHORT': 'U16', 'UCHAR': 'U8'}
    return tuple(scalar.get(token) for token in descriptor.split('_FTYPE_', 1)[1].split('_')
                 if token not in ('VOID', 'COUNT', 'CONVERT', 'PTEST'))


# Upper bound on match arms per generated function. The repository census
# counts functions over 300 lines as a budget (`fns_over_300`); a table that
# grows with every builtin must therefore be split, never re-baselined.
MAX_ARMS_PER_FN = 200


def emit_chunked_lookup(lines, name, signature, entries, arm_body):
    """Emit `name(name) -> Option<...>` as a chain of bounded `match` functions.

    `entries` is a list of (payload, names) groups, in the dictionary order the
    caller wants; each group becomes one `|`-joined arm whose right-hand side is
    `arm_body(payload)`. Groups are
    packed into chunk functions of at most MAX_ARMS_PER_FN name lines, and the
    public function tries the chunks in order. A name appears in exactly one
    group, so the chain returns the same value a single `match` would.
    """
    chunks = []
    current = []
    arms = 0
    for payload, names in entries:
        if current and arms + len(names) > MAX_ARMS_PER_FN:
            chunks.append(current)
            current, arms = [], 0
        current.append((payload, names))
        arms += len(names)
    if current:
        chunks.append(current)
    chunk_names = [f'{name}_{index}' for index in range(len(chunks))]
    for chunk_name, chunk in zip(chunk_names, chunks):
        lines += ['#[rustfmt::skip]', f'fn {chunk_name}(name: &str) -> {signature} {{',
                  '    Some(match name {']
        for payload, names in chunk:
            for index, arm in enumerate(sorted(names)):
                lines.append(('        ' if index == 0 else '        | ') + f'"{arm}"')
            lines[-1] += f' => {arm_body(payload)},'
        lines += ['        _ => return None,', '    })', '}', '']
    body = [f'    {chunk_names[0]}(name)']
    body += [f'        .or_else(|| {chunk}(name))' for chunk in chunk_names[1:]]
    lines += ['#[rustfmt::skip]', f'pub(crate) fn {name}(name: &str) -> {signature} {{', *body, '}', '']


def generate():
    groups = defaultdict(list)
    seen = set()
    only64 = []
    argument_groups = defaultdict(list)
    scalar_groups = defaultdict(list)
    for line in FACTS.read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        name, descriptor, mode = line.split('\t')
        if name in seen:
            raise ValueError(f'duplicate builtin: {name}')
        seen.add(name)
        if mode == "x86_64":
            only64.append(name)
        elif mode != "both":
            raise ValueError(f"unknown mode: {mode}")
        result = descriptor.split('_FTYPE_', 1)[0]
        groups[result_expression(result)].append(name)
        argument_groups[argument_vector_widths(descriptor)].append(name)
        scalar_groups[argument_scalar_types(descriptor)].append(name)
    lines = ['//! Generated by scripts/gen_x86_builtin_types.py; do not edit.',
             '//! Canonical GNU builtin C result types, independent of their IR carrier.',
             '//! See engineering/isa/gnu-x86-builtin-types.tsv for provenance.', '',
             'use super::types::{CType, IrType};', '']
    emit_chunked_lookup(lines, 'result_type', 'Option<CType>',
                        sorted(groups.items()),
                        lambda expression: expression)
    lines += ['#[rustfmt::skip]',
              'pub(crate) fn requires_64_bit(name: &str) -> bool {', '    matches!(name,']
    for index, name in enumerate(only64):
        lines.append(('        ' if index == 0 else '        | ') + f'"{name}"')
    lines += ['    )', '}', '',
              '/// Canonical vector argument byte widths; zero marks scalar/address operands.']
    emit_chunked_lookup(lines, 'argument_vector_widths', "Option<&'static [usize]>",
                        sorted(argument_groups.items()),
                        lambda widths: '&[' + ', '.join(map(str, widths)) + ']')
    lines += ['/// C scalar parameter conversions; vectors and addresses remain object operands.']
    emit_chunked_lookup(lines, 'argument_scalar_types', "Option<&'static [Option<IrType>]>",
                        sorted(scalar_groups.items(), key=lambda item: str(item[0])),
                        lambda types: '&[' + ', '.join(
                            f'Some(IrType::{ty})' if ty else 'None' for ty in types) + ']')
    return '\n'.join(lines)


def c_type(token):
    scalar = {'VOID': 'void', 'INT': 'int', 'SI': 'int', 'UINT': 'unsigned int',
              'INT64': 'long long', 'UINT64': 'unsigned long long',
              'LONGLONG': 'long long', 'ULONGLONG': 'unsigned long long',
              'USHORT': 'unsigned short', 'UCHAR': 'unsigned char'}
    pointer = {'PCCHAR': 'const char *', 'PCHAR': 'char *', 'PV2DI': 'tV2DI *',
               'PINT': 'int *', 'PLONGLONG': 'long long *', 'PDOUBLE': 'double *',
               'PUNSIGNED': 'unsigned int *', 'PCDOUBLE': 'const double *',
               'PCFLOAT': 'const float *', 'PFLOAT': 'float *',
               'PULONGLONG': 'unsigned long long *'}
    if token in scalar:
        return scalar[token]
    if token in pointer:
        return pointer[token]
    if re.fullmatch(r'V\d+(QI|HI|SI|DI|SF|DF)', token):
        return 't' + token
    # Vector pointers: `PV4DI` is `tV4DI *`; `PCV8SF` is `const tV8SF *`.
    pointed = re.fullmatch(r'P(C?)(V\d+(?:QI|HI|SI|DI|SF|DF))', token)
    if pointed:
        return ('const ' if pointed[1] else '') + 't' + pointed[2] + ' *'
    raise ValueError(f'unmapped GNU builtin argument descriptor: {token}')


def contract_source():
    rows = []
    vectors = set()
    for line in FACTS.read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        name, descriptor, mode = line.split('\t')
        result, args = descriptor.split('_FTYPE_', 1)
        arguments = [t for t in args.split('_') if t not in ('VOID', 'COUNT', 'CONVERT', 'PTEST')]
        for token in [result, *arguments, 'V2DI']:
            # A vector pointer (`PV4DI`, `PCV8SF`) needs its element typedef too.
            base = re.sub(r'^PC?(?=V\d)', '', token)
            if re.fullmatch(r'V\d+(QI|HI|SI|DI|SF|DF)', base):
                vectors.add(base)
        rows.append((name, result, arguments, mode))
    lines = ['/* Generated by scripts/gen_x86_builtin_types.py. */',
             '#include <stdio.h>', '#include <string.h>']
    elements = {'QI': 'char', 'HI': 'short', 'SI': 'int', 'DI': 'long long', 'SF': 'float', 'DF': 'double'}
    for token in sorted(vectors):
        match = re.fullmatch(r'V(\d+)(QI|HI|SI|DI|SF|DF)', token)
        size = int(match[1]) * ELEMENTS[match[2]][1]
        lines.append(f'typedef {elements[match[2]]} t{token} __attribute__((vector_size({size})));')
    runtime = []
    for index, (name, result, arguments, mode) in enumerate(rows):
        expressions = []
        for token in arguments:
            cty = c_type(token)
            expressions.append(f'({cty}){{0}}' if token.startswith('V') else f'({cty})0')
        call = f'{name}({", ".join(expressions)})'
        only64 = mode == 'x86_64'
        if only64:
            lines.append('#ifdef __x86_64__')
        lines.append(f'_Static_assert(__builtin_types_compatible_p(__typeof__({call}), {c_type(result)}), "{name} result type");')
        if only64:
            lines.append('#endif')
        # VNNI (AVX-VNNI/AVX512-VNNI) and SHA-512 are beyond the AVX2 host this
        # fixture runs on: retain their type contracts without executing
        # instructions the host need not implement (a SHA-512 probe on a CPU
        # without `sha512` faults with SIGILL, both here and on GitHub runners).
        if result.startswith('V') and result != 'VOID' and not name.startswith(RUNTIME_EXEMPT_PREFIXES):
            parameters = ', '.join(f'{c_type(t)} a{i}' for i, t in enumerate(arguments) if t.startswith('V') or '*' in c_type(t))
            immediate = '24' if re.search(r'(palignr128|ps[lr]ldqi(?:128|256))$', name) else '1'
            operands = [f'a{i}' if t.startswith('V') or '*' in c_type(t) else immediate for i, t in enumerate(arguments)]
            lines += [f'__attribute__((noinline)) static {c_type(result)} probe{index}({parameters or "void"})',
                      '{', f'    return {name}({", ".join(operands)});', '}']
            runtime.append((index, result, arguments))
    lines += ['int main(void)', '{', '    unsigned char storage[128] __attribute__((aligned(64)));',
              '    for (int i = 0; i < 128; ++i) storage[i] = (unsigned char)(i * 13 + 37);']
    for index, result, arguments in runtime:
        lines.append('    {')
        values = []
        for i, token in enumerate(arguments):
            cty = c_type(token)
            if token.startswith('V'):
                lines += [f'        {cty} a{i};', f'        memcpy(&a{i}, storage + {i * 7}, sizeof(a{i}));']
                values.append(f'a{i}')
            elif '*' in cty:
                values.append(f'({cty})storage')
        lines += [f'        {c_type(result)} result = probe{index}({", ".join(values)});',
                  '        unsigned char bytes[sizeof(result)];', '        memcpy(bytes, &result, sizeof(result));',
                  f'        printf("{index}:");',
                  '        for (unsigned i = 0; i < sizeof(result); ++i) printf("%02x", bytes[i]);',
                  '        puts("");', '    }']
    lines += ['    return 0;', '}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in ((OUTPUT, generate()), (CONTRACT, contract_source())):
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.error(f'native x86 builtin contract is stale: {path}')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
