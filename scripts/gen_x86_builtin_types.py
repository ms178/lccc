#!/usr/bin/env python3
"""Generate native C result contracts from checked-in GCC type facts."""
import argparse
from collections import defaultdict
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
FACTS = ROOT / 'engineering/isa/gnu-x86-builtin-types.tsv'
OUTPUT = ROOT / 'src/common/x86_builtin_types.rs'
CONTRACT = ROOT / 'tests/regression/gnu_native_builtin_types.c'
SCALARS = {'VOID': 'Void', 'INT': 'Int', 'UINT': 'UInt',
           'INT64': 'LongLong', 'UINT64': 'ULongLong'}
ELEMENTS = {'QI': ('Char', 1), 'HI': ('Short', 2), 'SI': ('Int', 4),
            'DI': ('LongLong', 8), 'SF': ('Float', 4), 'DF': ('Double', 8)}


def result_expression(token):
    if token in SCALARS:
        return f'CType::{SCALARS[token]}'
    match = re.fullmatch(r'V(\d+)(QI|HI|SI|DI|SF|DF)', token)
    if not match:
        raise ValueError(f'unmapped GNU builtin result descriptor: {token}')
    element, size = ELEMENTS[match[2]]
    return f'CType::Vector(Box::new(CType::{element}), {int(match[1]) * size})'


def generate():
    groups = defaultdict(list)
    seen = set()
    only64 = []
    for line in FACTS.read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        name, descriptor, mode = line.split('\t')
        if name in seen:
            raise ValueError(f'duplicate builtin: {name}')
        seen.add(name)
        if mode == "x86_64":
            only64.append(name)
        elif mode != "both":
            raise ValueError(f"unknown mode: {mode}")
        result = descriptor.split('_FTYPE_', 1)[0]
        groups[result_expression(result)].append(name)
    lines = ['//! Generated by scripts/gen_x86_builtin_types.py; do not edit.',
             '//! Canonical GNU builtin C result types, independent of their IR carrier.',
             '//! See engineering/isa/gnu-x86-builtin-types.tsv for provenance.', '',
             'use super::types::CType;', '',
             '#[rustfmt::skip]',
             'pub(crate) fn result_type(name: &str) -> Option<CType> {',
             '    Some(match name {']
    for expression, names in sorted(groups.items()):
        for index, name in enumerate(sorted(names)):
            prefix = '        ' if index == 0 else '        | '
            lines.append(f'{prefix}"{name}"')
        lines[-1] += f' => {expression},'
    lines += ['        _ => return None,', '    })', '}', '', '#[rustfmt::skip]',
              'pub(crate) fn requires_64_bit(name: &str) -> bool {', '    matches!(name,']
    for index, name in enumerate(only64):
        lines.append(('        ' if index == 0 else '        | ') + f'"{name}"')
    lines += ['    )', '}', '']
    return '\n'.join(lines)


def c_type(token):
    scalar = {'VOID': 'void', 'INT': 'int', 'SI': 'int', 'UINT': 'unsigned int',
              'INT64': 'long long', 'UINT64': 'unsigned long long',
              'LONGLONG': 'long long', 'USHORT': 'unsigned short', 'UCHAR': 'unsigned char'}
    pointer = {'PCCHAR': 'const char *', 'PCHAR': 'char *', 'PV2DI': 'tV2DI *',
               'PINT': 'int *', 'PLONGLONG': 'long long *', 'PDOUBLE': 'double *',
               'PUNSIGNED': 'unsigned int *', 'PCDOUBLE': 'const double *',
               'PCFLOAT': 'const float *'}
    if token in scalar:
        return scalar[token]
    if token in pointer:
        return pointer[token]
    if re.fullmatch(r'V\d+(QI|HI|SI|DI|SF|DF)', token):
        return 't' + token
    raise ValueError(f'unmapped GNU builtin argument descriptor: {token}')


def contract_source():
    rows = []
    vectors = set()
    for line in FACTS.read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        name, descriptor, mode = line.split('\t')
        result, args = descriptor.split('_FTYPE_', 1)
        arguments = [t for t in args.split('_') if t not in ('VOID', 'COUNT', 'CONVERT', 'PTEST')]
        for token in [result, *arguments, 'V2DI']:
            if re.fullmatch(r'V\d+(QI|HI|SI|DI|SF|DF)', token):
                vectors.add(token)
        rows.append((name, result, arguments, mode))
    lines = ['/* Generated by scripts/gen_x86_builtin_types.py. */',
             '#include <stdio.h>', '#include <string.h>']
    elements = {'QI': 'char', 'HI': 'short', 'SI': 'int', 'DI': 'long long', 'SF': 'float', 'DF': 'double'}
    for token in sorted(vectors):
        match = re.fullmatch(r'V(\d+)(QI|HI|SI|DI|SF|DF)', token)
        size = int(match[1]) * ELEMENTS[match[2]][1]
        lines.append(f'typedef {elements[match[2]]} t{token} __attribute__((vector_size({size})));')
    runtime = []
    for index, (name, result, arguments, mode) in enumerate(rows):
        expressions = []
        for token in arguments:
            cty = c_type(token)
            expressions.append(f'({cty}){{0}}' if token.startswith('V') else f'({cty})0')
        call = f'{name}({", ".join(expressions)})'
        only64 = mode == 'x86_64'
        if only64:
            lines.append('#ifdef __x86_64__')
        lines.append(f'_Static_assert(__builtin_types_compatible_p(__typeof__({call}), {c_type(result)}), "{name} result type");')
        if only64:
            lines.append('#endif')
        # VNNI is beyond SSE4/AVX2: retain its type contracts without executing
        # instructions the requested AVX2 host need not implement.
        if result.startswith('V') and result != 'VOID' and not name.startswith('__builtin_ia32_vpdp'):
            parameters = ', '.join(f'{c_type(t)} a{i}' for i, t in enumerate(arguments) if t.startswith('V') or '*' in c_type(t))
            immediate = '24' if re.search(r'(palignr128|ps[lr]ldqi(?:128|256))$', name) else '1'
            operands = [f'a{i}' if t.startswith('V') or '*' in c_type(t) else immediate for i, t in enumerate(arguments)]
            lines += [f'__attribute__((noinline)) static {c_type(result)} probe{index}({parameters or "void"})',
                      '{', f'    return {name}({", ".join(operands)});', '}']
            runtime.append((index, result, arguments))
    lines += ['int main(void)', '{', '    unsigned char storage[128] __attribute__((aligned(64)));',
              '    for (int i = 0; i < 128; ++i) storage[i] = (unsigned char)(i * 13 + 37);']
    for index, result, arguments in runtime:
        lines.append('    {')
        values = []
        for i, token in enumerate(arguments):
            cty = c_type(token)
            if token.startswith('V'):
                lines += [f'        {cty} a{i};', f'        memcpy(&a{i}, storage + {i * 7}, sizeof(a{i}));']
                values.append(f'a{i}')
            elif '*' in cty:
                values.append(f'({cty})storage')
        lines += [f'        {c_type(result)} result = probe{index}({", ".join(values)});',
                  '        unsigned char bytes[sizeof(result)];', '        memcpy(bytes, &result, sizeof(result));',
                  f'        printf("{index}:");',
                  '        for (unsigned i = 0; i < sizeof(result); ++i) printf("%02x", bytes[i]);',
                  '        puts("");', '    }']
    lines += ['    return 0;', '}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in ((OUTPUT, generate()), (CONTRACT, contract_source())):
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.error(f'native x86 builtin contract is stale: {path}')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
