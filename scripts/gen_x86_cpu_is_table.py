#!/usr/bin/env python3
"""Generate src/common/cpu_is_table.rs: the names `__builtin_cpu_is` accepts.

GCC lowers `__builtin_cpu_is("name")` to one comparison against libgcc's
`__cpu_model` (`struct __processor_model { unsigned vendor, type, subtype;
unsigned features[1]; }`): `cmpl $VALUE, __cpu_model+OFFSET`. The values are
libgcc ABI (`enum processor_vendor/types/subtypes`), so lccc lowers the
builtin to the same comparison and needs exactly GCC's (name, field, value)
triples.

Nothing is transcribed. The candidate names are the entries of GCC's
`processor_alias_table` (`gcc/common/config/i386/i386-common.cc`); GCC 16.2
itself decides which are accepted and, from its own assembly, which field
and value each one compares. Every measured value is cross-checked against
the ordinal of the alias entry's libgcc enum constant
(`gcc/common/config/i386/i386-cpuinfo.h`).

GCC documents names it does not accept (`gcc/doc/extend.texi`; GCC 16.2:
`amdfam1ah`, the `__cpu_type` libgcc stores on Zen 5/6). A documented name
whose spelling is exactly a libgcc enum constant is accepted with that
constant's ordinal, the value libgcc's `__cpu_indicator_init` stores.

Usage (sources from the oracle GCC's tree):
    GCC=gcc-16 scripts/gen_x86_cpu_is_table.py --gcc-src DIR [--check]
where DIR holds i386-common.cc, i386-cpuinfo.h and extend.texi.
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "src/common/cpu_is_table.rs"
FIELDS = {0: "Vendor", 4: "Type", 8: "Subtype"}
CMP_RE = re.compile(r"cmpl\s+\$(\d+),\s*__cpu_model(?:\+(\d+))?\(%rip\)")


def alias_names(common: Path) -> list[str]:
    text = common.read_text(encoding="utf-8")
    body = text.split("processor_alias_table[] =", 1)[1].split("\n};", 1)[0]
    names: list[str] = []
    for name in re.findall(r'^\s*\{\s*"([^"]+)"', body, re.M):
        if name not in names:
            names.append(name)
    return names


def enum_ordinals(header: Path) -> dict[str, tuple[str, int]]:
    """Constant -> (field, value) for libgcc's vendor/type/subtype enums."""
    text = header.read_text(encoding="utf-8")
    out: dict[str, tuple[str, int]] = {}
    for enum, field in (("processor_vendor", "Vendor"), ("processor_types", "Type"),
                        ("processor_subtypes", "Subtype")):
        body = text.split(f"enum {enum}\n{{", 1)[1].split("};", 1)[0]
        body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
        value = -1
        for item in (x.strip() for x in body.split(",")):
            if not item:
                continue
            name, _, explicit = (p.strip() for p in item.partition("="))
            if explicit:
                value = int(explicit) if explicit.isdigit() else out[explicit][1]
            else:
                value += 1
            out.setdefault(name, (field, value))
    return out


def alias_models(common: Path) -> dict[str, str]:
    """Alias-table name -> libgcc enum constant of its model, if any."""
    text = common.read_text(encoding="utf-8")
    body = text.split("processor_alias_table[] =", 1)[1].split("\n};", 1)[0]
    out = {}
    for entry in re.findall(r'\{\s*"([^"]+)"(.*?)\}', body, re.S):
        m = re.search(r"M_(?:VENDOR|CPU_TYPE|CPU_SUBTYPE)\s*\((\w+)\)", entry[1])
        if m:
            out.setdefault(entry[0], m.group(1))
    return out


def documented(texi: Path) -> list[str]:
    text = texi.read_text(encoding="utf-8")
    start = [m.start() for m in re.finditer(r"@defbuiltin\{int __builtin_cpu_is", text)][-1]
    return re.findall(r"^@item (\S+)", text[start:text.index("@enddefbuiltin", start)], re.M)


def measure(gcc: str, name: str) -> tuple[str, int] | None:
    src = f'int f(void) {{ return __builtin_cpu_is("{name}"); }}\n'
    with tempfile.TemporaryDirectory() as td:
        c = Path(td) / "c.c"
        c.write_text(src, encoding="utf-8")
        r = subprocess.run([gcc, "-O2", "-S", "-o", "-", str(c)], capture_output=True,
                           text=True, env={**os.environ, "LC_ALL": "C"})
    if r.returncode != 0:
        if "parameter to builtin not valid" not in r.stderr:
            sys.exit(f"{name}: unexpected GCC failure:\n{r.stderr}")
        return None
    hits = CMP_RE.findall(r.stdout)
    if len(hits) != 1:
        sys.exit(f"{name}: expected one __cpu_model comparison, got:\n{r.stdout}")
    value, offset = hits[0]
    return FIELDS[int(offset or 0)], int(value)


def render(gcc_version: str, rows: list[tuple[str, str, int]]) -> str:
    lines = [
        "//! Generated by `scripts/gen_x86_cpu_is_table.py` from GCC "
        f"{gcc_version}; do not edit.",
        "//!",
        "//! The names `__builtin_cpu_is` accepts and the libgcc `__cpu_model` field",
        "//! and value each compares, measured from GCC's own code generation.",
        "",
        "/// The `__cpu_model` field a name compares (`struct __processor_model`).",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub enum CpuModelField {",
        "    /// `__cpu_vendor`, byte offset 0.",
        "    Vendor,",
        "    /// `__cpu_type`, byte offset 4.",
        "    Type,",
        "    /// `__cpu_subtype`, byte offset 8.",
        "    Subtype,",
        "}",
        "",
        "impl CpuModelField {",
        "    /// Byte offset of the field in `__cpu_model`.",
        "    #[must_use]",
        "    pub const fn offset(self) -> i64 {",
        "        match self {",
        "            CpuModelField::Vendor => 0,",
        "            CpuModelField::Type => 4,",
        "            CpuModelField::Subtype => 8,",
        "        }",
        "    }",
        "}",
        "",
        "/// libgcc's `struct __processor_model __cpu_model`.",
        'pub const MODEL_SYMBOL: &str = "__cpu_model";',
        "",
        "/// libgcc's idempotent initialiser of [`MODEL_SYMBOL`]: it returns at once",
        "/// when `__cpu_vendor` is already nonzero, and it stores a nonzero vendor",
        "/// (`VENDOR_OTHER`) even when CPUID is unavailable.",
        'pub const INIT_SYMBOL: &str = "__cpu_indicator_init";',
        "",
        "/// The field and value `__builtin_cpu_is(name)` compares, if `name` is valid.",
        "#[must_use]",
        "pub fn lookup(name: &str) -> Option<(CpuModelField, u32)> {",
        "    CPU_IS_TABLE",
        "        .iter()",
        "        .find(|(n, _, _)| *n == name)",
        "        .map(|&(_, field, value)| (field, value))",
        "}",
        "",
        "/// `(name, field, value)` for every valid name.",
        "pub const CPU_IS_TABLE: &[(&str, CpuModelField, u32)] = &[",
    ]
    lines += [f'    ("{n}", CpuModelField::{f}, {v}),' for n, f, v in rows]
    lines += [
        "];",
        "",
        "#[cfg(test)]",
        "mod tests {",
        "    use super::*;",
        "",
        "    #[test]",
        "    fn names_are_unique_and_values_are_libgcc_enumerators() {",
        "        for (i, (name, _, value)) in CPU_IS_TABLE.iter().enumerate() {",
        "            assert!(*value != 0, \"{name}: libgcc enumerators start at 1\");",
        "            assert!(",
        "                CPU_IS_TABLE[..i].iter().all(|(n, _, _)| n != name),",
        "                \"{name} listed twice\"",
        "            );",
        "        }",
        "        assert_eq!(lookup(\"amdfam1ah\"), Some((CpuModelField::Type, 20)));",
        "        assert_eq!(lookup(\"x86-64\"), None);",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gcc-src", required=True, type=Path,
                    help="directory with the oracle GCC's i386-common.cc, "
                         "i386-cpuinfo.h and extend.texi")
    ap.add_argument("--check", action="store_true", help="fail if the table is stale")
    args = ap.parse_args()
    gcc = os.environ.get("GCC", "gcc-16")
    version = subprocess.run([gcc, "-dumpfullversion"], capture_output=True,
                             text=True).stdout.strip()
    ordinals = enum_ordinals(args.gcc_src / "i386-cpuinfo.h")
    models = alias_models(args.gcc_src / "i386-common.cc")
    rows = []
    for name in alias_names(args.gcc_src / "i386-common.cc"):
        got = measure(gcc, name)
        if got is None:
            continue
        if ordinals.get(models.get(name, "")) != got:
            sys.exit(f"{name}: GCC compares {got}, but its alias entry's libgcc "
                     f"constant {models.get(name)} is {ordinals.get(models.get(name, ''))}")
        rows.append((name, *got))
    accepted = {r[0] for r in rows}
    for name in documented(args.gcc_src / "extend.texi"):
        if name in accepted:
            continue
        const = next((c for c in (name.upper(), f"VENDOR_{name.upper()}") if c in ordinals),
                     None)
        if const is None:
            sys.exit(f"{name}: documented, rejected by GCC, and not a libgcc constant")
        rows.append((name, *ordinals[const]))
    text = render(version, rows)
    if args.check:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(REPO)} is stale; regenerate", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(REPO)}: {len(rows)} names, current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}: {len(rows)} names")
    return 0


if __name__ == "__main__":
    sys.exit(main())
