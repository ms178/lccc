#!/usr/bin/env python3
"""AUD-HYGIENE-1: replay every crash/miscompile reproducer in `artifacts/repros/`.

The directory is the compiler's scar tissue: 97 programs captured when lccc
crashed, miscompiled or disagreed with GCC.  The audit's question was whether
they still reproduce -- "add a replay gate (every file must now compile and run
identically to GCC) or archive the ones that no longer reproduce".  This gate is
that replay, and the answer it was written from is: **none of them reproduce**.

The one methodological trap, which is why an unpinned replay finds 29 failures
on a tree that has none, is the ISA.  lccc's documented project baseline is
x86-64-v3 (FMA available, and its backend contracts `a*b+c` at every
optimisation level, including -O0); GCC's default is plain x86-64 (no FMA).
Comparing the two defaults measures FMA contraction, not codegen:

    unpinned (lccc v3 vs gcc v1)          68 match, 29 differ
    -march=x86-64 on both                 94 match,  3 non-self-contained
    -march=x86-64-v3 -mno-fma on both     94 match,  3 non-self-contained

So both legs below PIN THE ISA and hand both compilers the same flags:

  * `-march=x86-64` -- the strict leg: no FMA anywhere, so any difference is a
    real semantic divergence;
  * `-march=x86-64-v3 -mno-fma` -- the wide-vector leg: AVX2 codegen is
    exercised (the configuration where the AUD-VABI-1/2 carriers live) while
    the contraction variable is removed.

The third file group is declared, not skipped silently: three csmith programs
`#include "csmith.h"`, a header the csmith tool generates and this repository
does not vendor, so they are not self-contained.  The list is checked in BOTH
directions -- if one of them starts compiling, the gate fails until the list is
updated, so "declared" cannot rot into "ignored".

The directory's file names encode the reproducer's configuration, and the
parser here is the contract:

    <name>_<seed>_-O<n>.c                        optimisation level
    <name>__env_<K>-<V>[,<K2>-<V2>]_-O<n>.c      environment variables

A file that does not fit either shape is a FAIL rather than a guess.

Usage:
    scripts/check_repro_replay.py                 # replay both legs
    scripts/check_repro_replay.py --legs v1       # one leg while bisecting
    scripts/check_repro_replay.py --self-test     # prove the harness catches a
                                                  # deliberate divergence
    scripts/check_repro_replay.py --list          # print the plan, run nothing

Exit codes: 0 = every reproducer compiles and agrees with GCC, 1 = a failure,
2 = usage error.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
REPRO_DIR = REPO / "artifacts" / "repros"
DEFAULT_LCCC = REPO / "target" / "fastbuild" / "lccc"

# Same flags for BOTH compilers: the point of the gate is like-for-like.
LEGS = {
    "v1": ("-march=x86-64",),
    "v3-nofma": ("-march=x86-64-v3", "-mno-fma"),
}

# Not self-contained: these include "csmith.h", which the csmith generator
# emits alongside its programs and this repository does not vendor.  Checked in
# both directions by `check_declared()`.
NON_SELF_CONTAINED = {
    "crash_csmith_20260981_-O0.c": 'includes "csmith.h" (generated by csmith, not vendored)',
    "miscompile_csmith_20260928_-O0.c": 'includes "csmith.h" (generated by csmith, not vendored)',
    "miscompile_csmith_20260945_-O0.c": 'includes "csmith.h" (generated by csmith, not vendored)',
}

OPT_RE = re.compile(r"(-O[0-3])(?:_[A-Za-z0-9_]+)?\.c$")
ENV_RE = re.compile(r"__env_([A-Za-z0-9_]+-[^_]*?(?:,[A-Za-z0-9_]+-[^_]*?)*)_-O")


def parse_repro(name: str) -> tuple[str, dict[str, str]]:
    """(optimisation level, environment) for a reproducer file name."""
    if not name.endswith(".c"):
        raise ValueError(f"{name}: not a .c reproducer")
    m = OPT_RE.search(name)
    if not m:
        raise ValueError(f"{name}: no -O<0..3> marker (see the naming contract)")
    opt = m.group(1)
    env: dict[str, str] = {}
    e = ENV_RE.search(name)
    if e:
        for part in e.group(1).split(","):
            knob, _, value = part.partition("-")
            if not knob or not _:
                raise ValueError(f"{name}: malformed __env_ segment {part!r}")
            env[knob] = value
    return opt, env


def run(cmd: list[str], env: dict[str, str] | None = None, timeout: int = 120):
    return subprocess.run(cmd, capture_output=True, env=env, timeout=timeout)


def classify(mine_rc: int, mine_out: bytes, orac_rc: int, orac_out: bytes) -> str:
    """The comparison, as a pure function so the self-test can prove it fires.

    A gate whose comparison always answers `agree` passes vacuously -- the
    AUD-VABI-1 gate shipped with exactly that defect (it diffed the wrong
    file).  Keeping the decision here lets `--self-test` drive every outcome
    with literal inputs instead of hoping some fixture diverges today.
    """
    if mine_rc != orac_rc:
        return "exit-mismatch"
    if mine_out != orac_out:
        return "output-mismatch"
    return "agree"


def replay_one(
    path: Path, lccc: str, gcc: str, flags: tuple[str, ...]
) -> tuple[str, str]:
    """Compile and run `path` with both compilers.  Returns (verdict, detail)."""
    opt, env_pairs = parse_repro(path.name)
    env = dict(os.environ)
    env.update(env_pairs)
    with tempfile.TemporaryDirectory() as td:
        l_bin = os.path.join(td, "lccc.out")
        g_bin = os.path.join(td, "gcc.out")
        comp = run([lccc, opt, *flags, str(path), "-o", l_bin], env=env)
        if comp.returncode != 0:
            first = (comp.stderr or comp.stdout).decode("utf-8", "replace").strip().splitlines()
            return "lccc-compile-fail", first[0] if first else "no diagnostic"
        oracle = run([gcc, opt, *flags, str(path), "-o", g_bin])
        if oracle.returncode != 0:
            first = oracle.stderr.decode("utf-8", "replace").strip().splitlines()
            return "oracle-compile-fail", first[0] if first else "no diagnostic"
        try:
            mine = run([l_bin], env=env, timeout=60)
        except subprocess.TimeoutExpired:
            return "lccc-timeout", "60 s"
        orac = run([g_bin], timeout=60)
        verdict = classify(mine.returncode, mine.stdout, orac.returncode, orac.stdout)
        if verdict == "exit-mismatch":
            return verdict, f"lccc rc={mine.returncode}, gcc rc={orac.returncode}"
        if verdict == "output-mismatch":
            l_out = mine.stdout.decode("utf-8", "replace").strip().splitlines()
            g_out = orac.stdout.decode("utf-8", "replace").strip().splitlines()
            return verdict, f"lccc={l_out[:1]!r} gcc={g_out[:1]!r}"
        return verdict, ""


def check_declared(files: list[str], lccc: str, gcc: str) -> list[str]:
    """The declared-not-self-contained list must still be exactly that."""
    problems = []
    for name, reason in NON_SELF_CONTAINED.items():
        path = REPRO_DIR / name
        if not path.exists():
            problems.append(f"declared non-self-contained file is missing: {name}")
            continue
        opt, _ = parse_repro(name)
        comp = run([lccc, opt, "-march=x86-64", "-fsyntax-only", str(path)])
        if comp.returncode == 0:
            problems.append(
                f"{name} now compiles; it is listed as {reason} -- drop it from "
                "NON_SELF_CONTAINED (the list must not rot into a skip list)"
            )
    return problems


def self_test(lccc: str, gcc: str) -> int:
    """Prove both halves of the harness: the decision table and the pipeline."""
    failures = []

    # 1. The comparison itself, driven with literal inputs so every outcome is
    #    exercised regardless of what any compiler happens to optimise today.
    cases = [
        ((0, b"a\n", 0, b"a\n"), "agree"),
        ((0, b"a\n", 0, b"b\n"), "output-mismatch"),
        ((0, b"a\n", 0, b""), "output-mismatch"),
        ((0, b"a\n", 3, b"a\n"), "exit-mismatch"),
    ]
    for args, want in cases:
        got = classify(*args)
        status = "ok  " if got == want else "FAIL"
        if got != want:
            failures.append(f"classify{args} = {got}, want {want}")
        print(f"  {status} decision table: rc/out {args[0]}/{args[1]!r} vs {args[2]}/{args[3]!r} -> {got}")

    # 2. The pipeline: a good program must come back `agree`, a broken one must
    #    come back with the compile verdict (not silently `agree`).
    with tempfile.TemporaryDirectory() as td:
        good = Path(td) / "selftest_ok_-O2.c"
        good.write_text('#include <stdio.h>\nint main(void){ printf("same\\n"); return 0; }\n')
        broken = Path(td) / "selftest_broken_-O2.c"
        broken.write_text("int main(void){ this is not C; }\n")
        verdict_ok, detail_ok = replay_one(good, lccc, gcc, ("-march=x86-64",))
        verdict_broken, _ = replay_one(broken, lccc, gcc, ("-march=x86-64",))
    if verdict_ok != "agree":
        failures.append(f"an identical program was not reported as agree (got {verdict_ok}: {detail_ok})")
    if verdict_broken != "lccc-compile-fail":
        failures.append(
            f"a program that cannot compile was reported as {verdict_broken}, "
            "not lccc-compile-fail -- the compile step is not wired in"
        )
    print(f"  {'ok  ' if verdict_ok == 'agree' else 'FAIL'} pipeline: identical program -> {verdict_ok}")
    print(f"  {'ok  ' if verdict_broken == 'lccc-compile-fail' else 'FAIL'} pipeline: broken program -> {verdict_broken}")

    for f in failures:
        print(f"FAIL: {f}", file=sys.stderr)
    if failures:
        return 1
    print("self-test: PASS (decision table and pipeline both exercised)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--lccc", default=os.environ.get("CCC", str(DEFAULT_LCCC)))
    ap.add_argument("--gcc", default=os.environ.get("GCC", "gcc"))
    ap.add_argument("--legs", default="all", choices=["all", "v1", "v3-nofma"])
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--list", action="store_true", help="print the plan and exit")
    ap.add_argument("-v", "--verbose", action="store_true")
    args = ap.parse_args()

    if args.self_test:
        return self_test(args.lccc, args.gcc)

    if not REPRO_DIR.is_dir():
        print(f"SKIP: {REPRO_DIR.relative_to(REPO)} does not exist", file=sys.stderr)
        return 0
    files = sorted(p.name for p in REPRO_DIR.glob("*.c"))
    if not files:
        print(f"FAIL: no reproducers in {REPRO_DIR.relative_to(REPO)}", file=sys.stderr)
        return 1

    if not Path(args.lccc).exists():
        print(f"SKIP: {args.lccc} not built", file=sys.stderr)
        return 0

    if args.list:
        for name in files:
            opt, env = parse_repro(name)
            mark = "declared" if name in NON_SELF_CONTAINED else "replay"
            print(f"{mark:8s} {opt:3s} {env!r:40s} {name}")
        print(f"{len(files)} reproducers, legs: {args.legs}")
        return 0

    problems = check_declared(files, args.lccc, args.gcc)
    for p in problems:
        print(f"FAIL: {p}", file=sys.stderr)
    if problems:
        return 1

    legs = LEGS if args.legs == "all" else {args.legs: LEGS[args.legs]}
    replayed = declared = 0
    bad: list[str] = []
    for leg, flags in legs.items():
        for name in files:
            if name in NON_SELF_CONTAINED:
                declared += 1
                continue
            verdict, detail = replay_one(REPO / "artifacts" / "repros" / name, args.lccc, args.gcc, flags)
            replayed += 1
            if verdict != "agree":
                bad.append(f"{leg}: {name}: {verdict} ({detail})")
            elif args.verbose:
                print(f"ok   {leg:8s} {name}")
        print(f"leg {leg} ({' '.join(flags)}): replayed {replayed} file(s) so far")

    for b in bad:
        print(f"FAIL: {b}", file=sys.stderr)
    if bad:
        print(
            "A reproducer that no longer agrees with GCC at a PINNED ISA is a "
            "real regression (or the file was added without one) -- the "
            "directory is the compiler's scar tissue, not a scratch pad.",
            file=sys.stderr,
        )
        return 1
    print(
        f"PASS: {replayed} reproducer replay(s) across {len(legs)} pinned leg(s) "
        f"all agree with GCC; {declared} declared non-self-contained"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
